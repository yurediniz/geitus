-- V9: estoque basico (Fase D) -- flag "controla estoque" no produto, saldo por
-- produto e movimentos de estoque imutaveis.
--
-- Migration aditiva (V1-V8 intactas, DEC-020). Ver
-- docs/modules/produtos-estoque.md (secao 3) e DEC-034.
--
-- Convencoes:
--  * Quantidade em NUMERIC(12,3), como os niveis de estoque de produtos.
--  * O saldo e derivado dos movimentos: so o servico de estoque o altera, na
--    mesma transacao do movimento, com a linha do saldo travada (FOR UPDATE).
--    Aqui ficam as regras que dependem da propria linha (saldo >= 0, coerencia
--    saldo_anterior + quantidade = saldo_novo, sinal por tipo).
--  * Isolamento por empresa (DEC-016): saldo e movimento pertencem a mesma
--    empresa do produto e do usuario, garantido por FKs COMPOSTAS.
--  * FKs para o produto com ON DELETE RESTRICT (DT-028): produto que
--    movimentou nao pode ser excluido fisicamente. A unica excecao (produto cujo
--    unico movimento e o estoque inicial do cadastro) e tratada pela aplicacao,
--    que apaga o movimento e o saldo antes do produto.

-- =====================================================================
-- Passo 1: controle de estoque por produto.
-- =====================================================================
-- Os produtos existentes passam a controlar estoque, com saldo zero (sem linha
-- em estoque_saldos).
ALTER TABLE produtos
    ADD COLUMN controla_estoque BOOLEAN NOT NULL DEFAULT true;

-- =====================================================================
-- Passo 2: saldo atual por produto.
-- =====================================================================
-- A linha nasce no primeiro movimento (INSERT ... ON CONFLICT DO NOTHING);
-- sem linha, o saldo e 0.
CREATE TABLE estoque_saldos (
    id            BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id    BIGINT        NOT NULL,
    produto_id    BIGINT        NOT NULL,
    saldo         NUMERIC(12,3) NOT NULL DEFAULT 0,
    atualizado_em TIMESTAMP     NOT NULL DEFAULT now(),
    CONSTRAINT fk_estoque_saldo_produto FOREIGN KEY (empresa_id, produto_id)
        REFERENCES produtos (empresa_id, id) ON DELETE RESTRICT,
    -- Um saldo por produto; alvo do ON CONFLICT e indice das leituras.
    CONSTRAINT uq_estoque_saldo_produto UNIQUE (empresa_id, produto_id),
    -- Nenhum movimento deixa o saldo negativo (decisao do usuario, spec 4.2).
    CONSTRAINT ck_estoque_saldo_nao_negativo CHECK (saldo >= 0)
);

-- =====================================================================
-- Passo 3: movimentos de estoque (so recebem insercoes).
-- =====================================================================
CREATE TABLE movimentos_estoque (
    id                 BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Identificador publico (DEC-019): gerado na aplicacao; o DEFAULT serve
    -- apenas a insercoes fora dela.
    uuid               UUID          NOT NULL DEFAULT gen_random_uuid(),
    empresa_id         BIGINT        NOT NULL,
    produto_id         BIGINT        NOT NULL,
    tipo               VARCHAR(10)   NOT NULL,
    motivo             VARCHAR(30)   NOT NULL,
    origem             VARCHAR(20)   NOT NULL,
    -- Variacao com sinal: + entrada, - saida; no ajuste, saldo contado - saldo.
    quantidade         NUMERIC(12,3) NOT NULL,
    saldo_anterior     NUMERIC(12,3) NOT NULL,
    saldo_novo         NUMERIC(12,3) NOT NULL,
    observacao         VARCHAR(200),
    usuario_id         BIGINT        NOT NULL,
    -- Chave enviada pela tela (um UUID por abertura do modal): o mesmo pedido
    -- repetido nao grava um segundo movimento. Nula no estoque inicial.
    chave_idempotencia UUID,
    criado_em          TIMESTAMP     NOT NULL DEFAULT now(),
    CONSTRAINT uq_movimento_estoque_uuid UNIQUE (uuid),
    CONSTRAINT fk_movimento_estoque_produto FOREIGN KEY (empresa_id, produto_id)
        REFERENCES produtos (empresa_id, id) ON DELETE RESTRICT,
    -- Usuarios nao sao excluidos fisicamente: RESTRICT (padrao). Alvo
    -- uq_usuario_empresa_id (V8).
    CONSTRAINT fk_movimento_estoque_usuario FOREIGN KEY (empresa_id, usuario_id)
        REFERENCES usuario (empresa_id, id),
    -- NULLs nao conflitam entre si: os movimentos sem chave nao colidem.
    CONSTRAINT uq_movimento_estoque_chave UNIQUE (empresa_id, chave_idempotencia),
    CONSTRAINT ck_movimento_estoque_tipo CHECK (tipo IN ('ENTRADA', 'SAIDA', 'AJUSTE')),
    CONSTRAINT ck_movimento_estoque_motivo CHECK (motivo IN (
        'COMPRA', 'DEVOLUCAO_CLIENTE', 'PERDA_AVARIA', 'VENCIDO', 'USO_INTERNO', 'DEVOLUCAO_FORNECEDOR',
        'CONTAGEM', 'OUTRO', 'ESTOQUE_INICIAL', 'VENDA')),
    CONSTRAINT ck_movimento_estoque_origem CHECK (origem IN ('AJUSTE_MANUAL', 'CADASTRO', 'VENDA')),
    -- Todo movimento muda o saldo.
    CONSTRAINT ck_movimento_estoque_quantidade CHECK (quantidade <> 0),
    CONSTRAINT ck_movimento_estoque_coerencia CHECK (saldo_novo = saldo_anterior + quantidade),
    CONSTRAINT ck_movimento_estoque_sinal CHECK (
        (tipo <> 'ENTRADA' OR quantidade > 0) AND (tipo <> 'SAIDA' OR quantidade < 0)),
    -- Matriz tipo x motivo (spec 4.3). Escrita como implicacoes: um tipo fora da
    -- lista cai no ck_movimento_estoque_tipo, nao aqui.
    CONSTRAINT ck_movimento_estoque_motivo_do_tipo CHECK (
        (tipo <> 'ENTRADA' OR motivo IN ('COMPRA', 'DEVOLUCAO_CLIENTE', 'ESTOQUE_INICIAL', 'OUTRO'))
        AND (tipo <> 'SAIDA' OR motivo IN ('PERDA_AVARIA', 'VENCIDO', 'USO_INTERNO', 'DEVOLUCAO_FORNECEDOR',
                                           'VENDA', 'OUTRO'))
        AND (tipo <> 'AJUSTE' OR motivo IN ('CONTAGEM', 'OUTRO'))),
    -- O cadastro so produz o estoque inicial...
    CONSTRAINT ck_movimento_estoque_cadastro CHECK (
        origem <> 'CADASTRO' OR (tipo = 'ENTRADA' AND motivo = 'ESTOQUE_INICIAL')),
    -- ... o estoque inicial so nasce no cadastro...
    CONSTRAINT ck_movimento_estoque_inicial CHECK (motivo <> 'ESTOQUE_INICIAL' OR origem = 'CADASTRO'),
    -- ... e e sempre o primeiro movimento do produto, partindo do saldo zero.
    CONSTRAINT ck_movimento_estoque_cadastro_do_zero CHECK (origem <> 'CADASTRO' OR saldo_anterior = 0),
    CONSTRAINT ck_movimento_estoque_saldos CHECK (saldo_anterior >= 0 AND saldo_novo >= 0)
);

-- Atende a consulta da aba Historico (por produto, do mais recente) e as FKs
-- RESTRICT na exclusao do produto.
CREATE INDEX ix_movimento_estoque_produto
    ON movimentos_estoque (empresa_id, produto_id, criado_em DESC, id DESC);

-- No maximo um estoque inicial por produto: a exclusao "so com o estoque
-- inicial" (spec 4.7) apaga exatamente esse movimento.
CREATE UNIQUE INDEX uq_movimento_estoque_inicial
    ON movimentos_estoque (empresa_id, produto_id)
    WHERE origem = 'CADASTRO';
