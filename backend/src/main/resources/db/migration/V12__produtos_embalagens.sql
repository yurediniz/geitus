-- V12: embalagens de venda do produto (Fase B3) -- lista de embalagens com
-- unidade, quantidade, preco opcional e "de compra"; codigos de barras das
-- embalagens; a unidade de compra vira a embalagem de compra; historico do
-- preco da embalagem; retrato da embalagem no movimento de estoque.
--
-- Migration aditiva (V1-V11 intactas, DEC-020). Ver
-- docs/modules/produtos-embalagens.md (secao 4) e DEC-037.
--
-- Convencoes:
--  * PK interna BIGINT identity (DEC-015), nunca exposta na API. O uuid publico
--    da embalagem e gerado na aplicacao (DEC-019); aqui o banco so o gera para
--    as embalagens criadas a partir da unidade de compra (mesmo padrao da V6).
--  * Isolamento por empresa (DEC-016): a embalagem pertence a mesma empresa do
--    produto e da unidade, e o codigo de barras de uma embalagem pertence ao
--    mesmo produto dela, garantido por FKs COMPOSTAS.
--  * Quantidade em NUMERIC(12,3) (unidades de venda por embalagem) e dinheiro
--    em NUMERIC(12,2), como as demais colunas de produtos.
--  * Dados inconvertiveis param a migration com erro: nada e descartado em
--    silencio.
--  * O rotulo da embalagem ("CX c/ 3 UN") e derivado e nao tem coluna na
--    embalagem; so o historico e o movimento guardam o rotulo do momento.
--    VARCHAR(60) cabe a maior sigla (20) + " c/ " + a maior quantidade
--    (13 caracteres) + " " + a maior sigla de venda (20).

-- =====================================================================
-- Passo 0: valida antes de transformar. Para com erro se alguma unidade de
-- compra nao puder virar embalagem; nada foi criado ainda.
-- =====================================================================
-- Inconvertiveis: unidade de compra diferente da de venda com fator <= 1, com
-- fracao numa unidade de venda nao fracionada ou com mais de 3 casas (a
-- quantidade da embalagem e NUMERIC(12,3)); ou a mesma unidade com fator
-- diferente de 1 (a aplicacao nunca aceitou, mas o banco nao impedia). A
-- mensagem traz o total e ate 10 produtos (empresa_id, numero) para corrigir.
DO $$
DECLARE
    inconvertiveis BIGINT;
    exemplos       TEXT;
BEGIN
    WITH problemas AS (
        SELECT p.empresa_id, p.numero
          FROM produtos p
          JOIN unidades_medida venda ON venda.id = p.unidade_id
         WHERE p.unidade_compra_id IS NOT NULL
           AND ((p.unidade_compra_id = p.unidade_id AND p.fator_conversao <> 1)
             OR (p.unidade_compra_id <> p.unidade_id
                 AND (p.fator_conversao <= 1
                   OR (p.fator_conversao <> trunc(p.fator_conversao) AND NOT venda.fracionada)
                   OR p.fator_conversao <> round(p.fator_conversao, 3))))
    )
    SELECT (SELECT count(*) FROM problemas),
           (SELECT string_agg('(' || empresa_id || ', ' || numero || ')', ', ')
              FROM (SELECT empresa_id, numero FROM problemas ORDER BY empresa_id, numero LIMIT 10) amostra)
      INTO inconvertiveis, exemplos;
    IF inconvertiveis > 0 THEN
        RAISE EXCEPTION 'V12: % produto(s) com unidade de compra que nao pode virar embalagem (fator ate 1, '
            'fracao em unidade de venda nao fracionada, mais de 3 casas ou mesma unidade com fator diferente '
            'de 1). Produtos (empresa_id, numero): %. Corrija o cadastro e rode a migracao de novo.',
            inconvertiveis, exemplos;
    END IF;
END $$;

-- =====================================================================
-- Passo 1: embalagens do produto (0..N; o limite de 10 e da aplicacao).
-- =====================================================================
CREATE TABLE produto_embalagens (
    id            BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid          UUID          NOT NULL,
    empresa_id    BIGINT        NOT NULL,
    produto_id    BIGINT        NOT NULL,
    unidade_id    BIGINT        NOT NULL,
    quantidade    NUMERIC(12,3) NOT NULL,
    preco         NUMERIC(12,2),
    de_compra     BOOLEAN       NOT NULL DEFAULT false,
    ordem         SMALLINT      NOT NULL,
    criado_em     TIMESTAMP     NOT NULL DEFAULT now(),
    atualizado_em TIMESTAMP     NOT NULL DEFAULT now(),
    CONSTRAINT uq_embalagem_uuid UNIQUE (uuid),
    -- A embalagem faz parte do cadastro do produto: sai junto com ele.
    CONSTRAINT fk_embalagem_produto FOREIGN KEY (empresa_id, produto_id)
        REFERENCES produtos (empresa_id, id) ON DELETE CASCADE,
    -- Unidade em uso nao e excluida (RESTRICT, padrao); sempre da mesma empresa.
    CONSTRAINT fk_embalagem_unidade FOREIGN KEY (empresa_id, unidade_id)
        REFERENCES unidades_medida (empresa_id, id),
    -- Sem duas embalagens com a mesma unidade e quantidade no produto (CX c/ 12
    -- e CX c/ 24 coexistem). DEFERRABLE INITIALLY DEFERRED: conferida no fim da
    -- transacao, para que duas embalagens possam trocar de unidade e quantidade
    -- entre si no mesmo salvamento (Review Focus 2). A aplicacao recusa a
    -- repeticao antes, e a edicao trava a linha do produto: a conferencia no
    -- commit e so a rede de seguranca.
    CONSTRAINT uq_embalagem_produto_unidade_quantidade UNIQUE (produto_id, unidade_id, quantidade)
        DEFERRABLE INITIALLY DEFERRED,
    -- Alvo da FK composta dos codigos de barras (o codigo e do mesmo produto).
    -- O prefixo (empresa_id, produto_id) tambem serve a FK do produto e ao
    -- ON DELETE CASCADE.
    CONSTRAINT uq_embalagem_empresa_produto_id UNIQUE (empresa_id, produto_id, id),
    CONSTRAINT ck_embalagem_quantidade CHECK (quantidade > 1),
    CONSTRAINT ck_embalagem_preco CHECK (preco IS NULL OR preco > 0),
    CONSTRAINT ck_embalagem_ordem CHECK (ordem >= 0)
);

-- No maximo uma embalagem de compra por produto.
CREATE UNIQUE INDEX uq_embalagem_de_compra ON produto_embalagens (produto_id) WHERE de_compra;

-- Serve a regra "unidade em uso" do cadastro de unidades e a FK da unidade.
CREATE INDEX idx_embalagem_unidade ON produto_embalagens (unidade_id);

-- =====================================================================
-- Passo 2: codigos de barras das embalagens.
-- =====================================================================
-- embalagem_id nulo = codigo da unidade de venda (MATCH SIMPLE: a FK so e
-- conferida com a coluna preenchida). A FK composta garante que a embalagem e
-- do mesmo produto (e empresa) do codigo. uq_codigo_barras_empresa (V7)
-- continua e passa a valer entre unidade e embalagens: um codigo pertence a um
-- unico produto ou embalagem da empresa.
ALTER TABLE produto_codigos_barras
    ADD COLUMN embalagem_id BIGINT,
    ADD CONSTRAINT fk_codigo_barras_embalagem FOREIGN KEY (empresa_id, produto_id, embalagem_id)
        REFERENCES produto_embalagens (empresa_id, produto_id, id) ON DELETE CASCADE;

-- Serve a listagem dos codigos da embalagem e o ON DELETE CASCADE.
CREATE INDEX idx_codigo_barras_embalagem ON produto_codigos_barras (embalagem_id);

-- =====================================================================
-- Passo 3: a unidade de compra vira a embalagem de compra.
-- =====================================================================
-- A unidade de compra igual a de venda (fator 1) nao gera embalagem: a
-- informacao e vazia. O fator passa de NUMERIC(12,4) para NUMERIC(12,3) sem
-- perda (o Passo 0 garante no maximo 3 casas).
INSERT INTO produto_embalagens (uuid, empresa_id, produto_id, unidade_id, quantidade, preco, de_compra, ordem)
SELECT gen_random_uuid(), p.empresa_id, p.id, p.unidade_compra_id, p.fator_conversao, NULL, true, 0
  FROM produtos p
 WHERE p.unidade_compra_id IS NOT NULL
   AND p.unidade_compra_id <> p.unidade_id
 ORDER BY p.id;

-- =====================================================================
-- Passo 4: sai a unidade de compra de produtos.
-- =====================================================================
DROP INDEX idx_produto_unidade_compra;

ALTER TABLE produtos
    DROP CONSTRAINT ck_produto_compra_coerente,
    DROP CONSTRAINT ck_produto_fator_positivo,
    DROP CONSTRAINT fk_produto_unidade_compra,
    DROP COLUMN unidade_compra_id,
    DROP COLUMN fator_conversao;

-- =====================================================================
-- Passo 5: historico do preco proprio da embalagem.
-- =====================================================================
-- Sem FK para a embalagem: a linha sobrevive a remocao dela, com o rotulo do
-- momento da alteracao.
ALTER TABLE produto_historico_precos
    ADD COLUMN embalagem_rotulo VARCHAR(60),
    DROP CONSTRAINT ck_historico_preco_campo,
    ADD CONSTRAINT ck_historico_preco_campo CHECK (campo IN ('CUSTO', 'PRECO_VENDA', 'PRECO_EMBALAGEM')),
    -- O rotulo vem so (e sempre) nas linhas do preco da embalagem.
    ADD CONSTRAINT ck_historico_preco_embalagem_rotulo
        CHECK ((campo = 'PRECO_EMBALAGEM') = (embalagem_rotulo IS NOT NULL)),
    ADD CONSTRAINT ck_historico_preco_embalagem_rotulo_valido
        CHECK (embalagem_rotulo IS NULL OR btrim(embalagem_rotulo) <> '');

-- =====================================================================
-- Passo 6: retrato da embalagem no movimento de estoque (ajuste informado em
-- embalagens). O movimento continua em unidades de venda.
-- =====================================================================
-- Sem FK para a embalagem: o movimento e imutavel e guarda o retrato.
ALTER TABLE movimentos_estoque
    ADD COLUMN embalagem_rotulo      VARCHAR(60),
    ADD COLUMN embalagem_quantidade  NUMERIC(12,3),
    ADD COLUMN quantidade_embalagens INTEGER,
    -- As tres nulas ou as tres preenchidas, com valores validos. Os IS NOT NULL
    -- explicitos evitam que uma comparacao com NULL deixe a CHECK passar.
    ADD CONSTRAINT ck_movimento_estoque_embalagem_completa CHECK (
        (embalagem_rotulo IS NULL AND embalagem_quantidade IS NULL AND quantidade_embalagens IS NULL)
        OR (embalagem_rotulo IS NOT NULL AND embalagem_quantidade IS NOT NULL AND quantidade_embalagens IS NOT NULL
            AND embalagem_quantidade > 1 AND quantidade_embalagens > 0)),
    -- Contagem e "zerar estoque" sao sempre na unidade de venda.
    ADD CONSTRAINT ck_movimento_estoque_embalagem_tipo CHECK (
        embalagem_rotulo IS NULL OR tipo IN ('ENTRADA', 'SAIDA')),
    -- O total em unidades e o numero de embalagens vezes o conteudo de cada uma.
    ADD CONSTRAINT ck_movimento_estoque_embalagem_total CHECK (
        embalagem_rotulo IS NULL OR abs(quantidade) = quantidade_embalagens * embalagem_quantidade),
    ADD CONSTRAINT ck_movimento_estoque_embalagem_rotulo_valido CHECK (
        embalagem_rotulo IS NULL OR btrim(embalagem_rotulo) <> '');
