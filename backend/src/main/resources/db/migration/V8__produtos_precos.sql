-- V8: precos do produto (Fase C) -- promocao por datas, atacado de uma faixa
-- e historico de custo e preco de venda.
--
-- Migration aditiva (V1-V7 intactas, DEC-020). Ver
-- docs/modules/produtos-precos.md (secao 3) e DEC-033.
--
-- Convencoes:
--  * Dinheiro em NUMERIC(12,2) e quantidade em NUMERIC(12,3), como as demais
--    colunas de produtos.
--  * As colunas novas nascem nulas: nenhum produto existente ganha promocao ou
--    atacado, e o historico comeca vazio (sem preenchimento retroativo).
--  * As comparacoes com o preco de venda e o preco minimo ficam no service
--    (mesmo criterio do preco_minimo, DEC-028); aqui ficam so as regras que
--    dependem da propria linha.
--  * Isolamento por empresa (DEC-016): a linha de historico pertence a mesma
--    empresa do produto e do usuario, garantido por FKs COMPOSTAS.

-- =====================================================================
-- Passo 1: promocao e atacado em produtos.
-- =====================================================================
ALTER TABLE produtos
    ADD COLUMN preco_promocional         NUMERIC(12,2),
    ADD COLUMN promocao_inicio           DATE,
    ADD COLUMN promocao_fim              DATE,
    ADD COLUMN preco_atacado             NUMERIC(12,2),
    ADD COLUMN quantidade_minima_atacado NUMERIC(12,3),
    ADD CONSTRAINT ck_produto_preco_promocional_positivo
        CHECK (preco_promocional IS NULL OR preco_promocional > 0),
    -- Tudo ou nada: preco, inicio e fim juntos, ou nenhum deles.
    ADD CONSTRAINT ck_produto_promocao_completa
        CHECK ((preco_promocional IS NULL AND promocao_inicio IS NULL AND promocao_fim IS NULL)
            OR (preco_promocional IS NOT NULL AND promocao_inicio IS NOT NULL AND promocao_fim IS NOT NULL)),
    -- Inicio e fim inclusivos; promocao de um dia so tem inicio = fim.
    ADD CONSTRAINT ck_produto_promocao_periodo
        CHECK (promocao_fim IS NULL OR promocao_inicio IS NULL OR promocao_fim >= promocao_inicio),
    ADD CONSTRAINT ck_produto_preco_atacado_positivo
        CHECK (preco_atacado IS NULL OR preco_atacado > 0),
    -- Tudo ou nada: preco e quantidade minima juntos, ou nenhum dos dois.
    ADD CONSTRAINT ck_produto_atacado_completo
        CHECK ((preco_atacado IS NULL) = (quantidade_minima_atacado IS NULL)),
    ADD CONSTRAINT ck_produto_quantidade_minima_atacado
        CHECK (quantidade_minima_atacado IS NULL OR quantidade_minima_atacado > 1);

-- =====================================================================
-- Passo 2: alvo da FK composta do usuario do historico.
-- =====================================================================
-- id ja e PK; o par (empresa_id, id) e unico por consequencia. A constraint
-- existe so para servir de alvo da FK composta abaixo.
ALTER TABLE usuario
    ADD CONSTRAINT uq_usuario_empresa_id UNIQUE (empresa_id, id);

-- =====================================================================
-- Passo 3: historico de custo e preco de venda (so recebe insercoes).
-- =====================================================================
CREATE TABLE produto_historico_precos (
    id             BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id     BIGINT        NOT NULL,
    produto_id     BIGINT        NOT NULL,
    campo          VARCHAR(20)   NOT NULL,
    valor_anterior NUMERIC(12,2),
    valor_novo     NUMERIC(12,2),
    usuario_id     BIGINT        NOT NULL,
    alterado_em    TIMESTAMP     NOT NULL DEFAULT now(),
    -- O historico faz parte do cadastro: sai junto com o produto (que so e
    -- excluido se nunca vendeu nem movimentou).
    CONSTRAINT fk_historico_preco_produto FOREIGN KEY (empresa_id, produto_id)
        REFERENCES produtos (empresa_id, id) ON DELETE CASCADE,
    -- Usuarios nao sao excluidos fisicamente: RESTRICT (padrao).
    CONSTRAINT fk_historico_preco_usuario FOREIGN KEY (empresa_id, usuario_id)
        REFERENCES usuario (empresa_id, id),
    CONSTRAINT ck_historico_preco_campo CHECK (campo IN ('CUSTO', 'PRECO_VENDA')),
    -- Toda linha registra uma mudanca real (NULL -> NULL tambem e barrado).
    CONSTRAINT ck_historico_preco_mudanca CHECK (valor_anterior IS DISTINCT FROM valor_novo),
    -- O preco de venda e obrigatorio no produto: nunca "removido".
    CONSTRAINT ck_historico_preco_venda_nao_nulo CHECK (campo <> 'PRECO_VENDA' OR valor_novo IS NOT NULL)
);

-- Atende a consulta da aba Historico (por produto, do mais recente) e o
-- ON DELETE CASCADE.
CREATE INDEX ix_historico_preco_produto
    ON produto_historico_precos (empresa_id, produto_id, alterado_em DESC, id DESC);
