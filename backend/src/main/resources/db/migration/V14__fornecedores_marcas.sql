-- V14: cadastros de Fabricantes/Marcas e de Fornecedores, os fornecedores do
-- produto (com o da ultima compra) e o fornecedor na entrada por compra
-- (Fase B5).
--
-- Migration aditiva (V1-V13 intactas, DEC-020). Ver
-- docs/modules/fornecedores-e-marcas.md (secao 7) e DEC-039.
--
-- Convencoes:
--  * PK interna BIGINT identity (DEC-015), nunca exposta; o identificador
--    publico e o uuid (DEC-019), gerado em Java. O DEFAULT do uuid e so rede de
--    seguranca (e o que a migracao do texto usa).
--  * Isolamento por empresa (DEC-016) no banco: toda ligacao entre cadastros
--    usa FK COMPOSTA (empresa_id, ...) -> (empresa_id, id). Um vinculo com
--    registro de outra empresa e recusado pelo banco, alem do service.
--  * marcas e o mesmo modelo de categorias (V6): arvore livre, nome unico entre
--    irmaos sem diferenciar maiusculas, sem ON DELETE CASCADE no pai.
--  * fornecedores.numero: 1, 2, 3... por empresa, pelo Numerador (tipo
--    FORNECEDOR), imutavel, como em produtos e clientes (V11).
--  * fornecedores.busca_normalizada e nome_normalizado: DERIVADAS, mantidas
--    pela aplicacao (TextoDeBusca) a cada gravacao, como em produtos (V10). A
--    busca reune razao social, nome fantasia e nomes dos representantes; o
--    documento e o numero sao comparados nas proprias colunas.
--  * Documento, CEP e telefones guardados so com digitos; UF em maiusculas;
--    textos aparados e vazio como NULL (CHECKs abaixo, alem do service).
--  * produtos.fornecedor_ultima_compra_id aponta para a LIGACAO
--    produto_fornecedores (FK de tres colunas): o banco garante que o
--    fornecedor da ultima compra esta na lista do produto. A FK e imediata (sem
--    DEFERRABLE): a aplicacao limpa o campo ANTES de apagar a ligacao.

-- =====================================================================
-- Passo 1: marcas (como categorias, V6).
-- =====================================================================
CREATE TABLE marcas (
    id            BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid          UUID         NOT NULL DEFAULT gen_random_uuid(),
    empresa_id    BIGINT       NOT NULL,
    parent_id     BIGINT,
    nome          VARCHAR(100) NOT NULL,
    ativo         BOOLEAN      NOT NULL DEFAULT true,
    criado_em     TIMESTAMP    NOT NULL DEFAULT now(),
    atualizado_em TIMESTAMP,
    CONSTRAINT fk_marca_empresa FOREIGN KEY (empresa_id) REFERENCES empresa (id),
    CONSTRAINT uq_marca_uuid UNIQUE (uuid),
    -- Alvo das FKs do pai, de produtos e de fornecedor_marcas.
    CONSTRAINT uq_marca_empresa_id UNIQUE (empresa_id, id),
    CONSTRAINT ck_marca_nome_valido CHECK (nome = btrim(nome) AND nome <> ''),
    CONSTRAINT ck_marca_pai_diferente CHECK (parent_id IS NULL OR parent_id <> id)
);

ALTER TABLE marcas
    ADD CONSTRAINT fk_marca_pai FOREIGN KEY (empresa_id, parent_id) REFERENCES marcas (empresa_id, id);

CREATE UNIQUE INDEX uq_marca_irmaos ON marcas (empresa_id, COALESCE(parent_id, 0), lower(nome));

CREATE INDEX idx_marca_pai ON marcas (parent_id);

-- =====================================================================
-- Passo 2: fornecedores.
-- =====================================================================
CREATE TABLE fornecedores (
    id                   BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid                 UUID         NOT NULL DEFAULT gen_random_uuid(),
    empresa_id           BIGINT       NOT NULL,
    numero               BIGINT       NOT NULL,
    tipo_pessoa          VARCHAR(2)   NOT NULL DEFAULT 'PJ',
    documento            VARCHAR(14),
    razao_social         VARCHAR(180) NOT NULL,
    nome_fantasia        VARCHAR(180),
    inscricao_estadual   VARCHAR(20),
    endereco_cep         VARCHAR(8),
    endereco_logradouro  VARCHAR(180),
    endereco_numero      VARCHAR(20),
    endereco_complemento VARCHAR(120),
    endereco_bairro      VARCHAR(120),
    endereco_municipio   VARCHAR(120),
    endereco_uf          VARCHAR(2),
    telefone             VARCHAR(20),
    email                VARCHAR(180),
    observacoes          VARCHAR(500),
    ativo                BOOLEAN      NOT NULL DEFAULT true,
    busca_normalizada    TEXT COLLATE "C" NOT NULL,
    nome_normalizado     TEXT COLLATE "C" NOT NULL,
    criado_em            TIMESTAMP    NOT NULL DEFAULT now(),
    atualizado_em        TIMESTAMP,
    CONSTRAINT fk_fornecedor_empresa FOREIGN KEY (empresa_id) REFERENCES empresa (id),
    CONSTRAINT uq_fornecedor_uuid UNIQUE (uuid),
    -- Alvo das FKs compostas (representantes, marcas, produtos e movimentos).
    CONSTRAINT uq_fornecedor_empresa_id UNIQUE (empresa_id, id),
    CONSTRAINT uq_fornecedor_empresa_numero UNIQUE (empresa_id, numero),
    CONSTRAINT ck_fornecedor_numero_positivo CHECK (numero >= 1),
    CONSTRAINT ck_fornecedor_tipo_pessoa CHECK (tipo_pessoa IN ('PJ', 'PF')),
    -- CNPJ (14 digitos) no PJ e CPF (11) no PF; os digitos verificadores sao do service.
    CONSTRAINT ck_fornecedor_documento CHECK (
        documento IS NULL
        OR (tipo_pessoa = 'PJ' AND documento ~ '^[0-9]{14}$')
        OR (tipo_pessoa = 'PF' AND documento ~ '^[0-9]{11}$')),
    CONSTRAINT ck_fornecedor_inscricao_estadual CHECK (
        inscricao_estadual IS NULL OR inscricao_estadual = 'ISENTO' OR inscricao_estadual ~ '^[0-9]{1,20}$'),
    CONSTRAINT ck_fornecedor_inscricao_so_pj CHECK (inscricao_estadual IS NULL OR tipo_pessoa = 'PJ'),
    CONSTRAINT ck_fornecedor_cep CHECK (endereco_cep IS NULL OR endereco_cep ~ '^[0-9]{8}$'),
    CONSTRAINT ck_fornecedor_uf CHECK (endereco_uf IS NULL OR endereco_uf IN (
        'AC', 'AL', 'AP', 'AM', 'BA', 'CE', 'DF', 'ES', 'GO', 'MA', 'MT', 'MS', 'MG', 'PA',
        'PB', 'PR', 'PE', 'PI', 'RJ', 'RN', 'RS', 'RO', 'RR', 'SC', 'SP', 'SE', 'TO')),
    CONSTRAINT ck_fornecedor_telefone CHECK (telefone IS NULL OR telefone ~ '^[0-9]{10,11}$'),
    -- Textos aparados e nao vazios (vazio vira NULL na aplicacao).
    CONSTRAINT ck_fornecedor_razao_social_valida CHECK (razao_social = btrim(razao_social) AND razao_social <> ''),
    CONSTRAINT ck_fornecedor_textos_aparados CHECK (
        (nome_fantasia IS NULL OR (nome_fantasia = btrim(nome_fantasia) AND nome_fantasia <> ''))
        AND (endereco_logradouro IS NULL OR (endereco_logradouro = btrim(endereco_logradouro)
                                             AND endereco_logradouro <> ''))
        AND (endereco_numero IS NULL OR (endereco_numero = btrim(endereco_numero) AND endereco_numero <> ''))
        AND (endereco_complemento IS NULL OR (endereco_complemento = btrim(endereco_complemento)
                                              AND endereco_complemento <> ''))
        AND (endereco_bairro IS NULL OR (endereco_bairro = btrim(endereco_bairro) AND endereco_bairro <> ''))
        AND (endereco_municipio IS NULL OR (endereco_municipio = btrim(endereco_municipio)
                                            AND endereco_municipio <> ''))
        AND (email IS NULL OR (email = btrim(email) AND email <> ''))
        AND (observacoes IS NULL OR (observacoes = btrim(observacoes) AND observacoes <> '')))
);

-- Documento unico por empresa, so quando informado (tambem serve a checagem do service).
CREATE UNIQUE INDEX uq_fornecedor_empresa_documento
    ON fornecedores (empresa_id, documento)
    WHERE documento IS NOT NULL;

-- Listagem: filtro de status e ordem por nome (desempate pelo id).
CREATE INDEX ix_fornecedor_empresa_ativo_nome
    ON fornecedores (empresa_id, ativo, nome_normalizado, id);

-- =====================================================================
-- Passo 3: representantes de venda do fornecedor (0..10; o limite e da aplicacao).
-- =====================================================================
CREATE TABLE fornecedor_representantes (
    id            BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid          UUID         NOT NULL DEFAULT gen_random_uuid(),
    empresa_id    BIGINT       NOT NULL,
    fornecedor_id BIGINT       NOT NULL,
    nome          VARCHAR(120) NOT NULL,
    telefone      VARCHAR(20),
    email         VARCHAR(180),
    ordem         SMALLINT     NOT NULL,
    CONSTRAINT uq_representante_uuid UNIQUE (uuid),
    CONSTRAINT fk_representante_fornecedor FOREIGN KEY (empresa_id, fornecedor_id)
        REFERENCES fornecedores (empresa_id, id) ON DELETE CASCADE,
    CONSTRAINT ck_representante_nome_valido CHECK (nome = btrim(nome) AND nome <> ''),
    CONSTRAINT ck_representante_telefone CHECK (telefone IS NULL OR telefone ~ '^[0-9]{10,11}$'),
    CONSTRAINT ck_representante_email CHECK (email IS NULL OR (email = btrim(email) AND email <> '')),
    CONSTRAINT ck_representante_ordem CHECK (ordem >= 0)
);

CREATE INDEX ix_representante_fornecedor ON fornecedor_representantes (empresa_id, fornecedor_id, ordem);

-- =====================================================================
-- Passo 4: marcas que o fornecedor vende (0..200; o limite e da aplicacao).
-- =====================================================================
CREATE TABLE fornecedor_marcas (
    empresa_id    BIGINT NOT NULL,
    fornecedor_id BIGINT NOT NULL,
    marca_id      BIGINT NOT NULL,
    CONSTRAINT pk_fornecedor_marcas PRIMARY KEY (empresa_id, fornecedor_id, marca_id),
    CONSTRAINT fk_fornecedor_marca_fornecedor FOREIGN KEY (empresa_id, fornecedor_id)
        REFERENCES fornecedores (empresa_id, id) ON DELETE CASCADE,
    -- A marca ligada a um fornecedor nao e excluida (a aplicacao responde 409 antes).
    CONSTRAINT fk_fornecedor_marca_marca FOREIGN KEY (empresa_id, marca_id)
        REFERENCES marcas (empresa_id, id) ON DELETE RESTRICT
);

CREATE INDEX ix_fornecedor_marca_marca ON fornecedor_marcas (marca_id);

-- =====================================================================
-- Passo 5: fornecedores do produto (a mesma lista vista dos dois lados; ate 20
-- por produto, limite da aplicacao).
-- =====================================================================
CREATE TABLE produto_fornecedores (
    empresa_id    BIGINT NOT NULL,
    produto_id    BIGINT NOT NULL,
    fornecedor_id BIGINT NOT NULL,
    -- Tambem e o alvo da FK do fornecedor da ultima compra (Passo 9).
    CONSTRAINT pk_produto_fornecedores PRIMARY KEY (empresa_id, produto_id, fornecedor_id),
    CONSTRAINT fk_produto_fornecedor_produto FOREIGN KEY (empresa_id, produto_id)
        REFERENCES produtos (empresa_id, id) ON DELETE CASCADE,
    CONSTRAINT fk_produto_fornecedor_fornecedor FOREIGN KEY (empresa_id, fornecedor_id)
        REFERENCES fornecedores (empresa_id, id) ON DELETE RESTRICT
);

CREATE INDEX ix_produto_fornecedor_fornecedor ON produto_fornecedores (fornecedor_id);

-- =====================================================================
-- Passo 6: colunas novas de produtos, do movimento de estoque e da numeracao.
-- =====================================================================
ALTER TABLE produtos
    ADD COLUMN marca_id                    BIGINT,
    ADD COLUMN fornecedor_ultima_compra_id BIGINT,
    ADD CONSTRAINT fk_produto_marca FOREIGN KEY (empresa_id, marca_id) REFERENCES marcas (empresa_id, id);

CREATE INDEX idx_produto_marca ON produtos (marca_id);

ALTER TABLE movimentos_estoque
    ADD COLUMN fornecedor_id BIGINT,
    ADD CONSTRAINT fk_movimento_estoque_fornecedor FOREIGN KEY (empresa_id, fornecedor_id)
        REFERENCES fornecedores (empresa_id, id) ON DELETE RESTRICT,
    -- O fornecedor so e informado no ajuste manual de entrada por compra (spec 6).
    ADD CONSTRAINT ck_movimento_estoque_fornecedor_so_na_compra CHECK (
        fornecedor_id IS NULL OR (tipo = 'ENTRADA' AND motivo = 'COMPRA' AND origem = 'AJUSTE_MANUAL'));

-- Contagem das entradas de um fornecedor (exclusao do fornecedor, spec 4.5).
CREATE INDEX ix_movimento_estoque_fornecedor
    ON movimentos_estoque (empresa_id, fornecedor_id)
    WHERE fornecedor_id IS NOT NULL;

ALTER TABLE numeracoes
    DROP CONSTRAINT ck_numeracao_tipo,
    ADD CONSTRAINT ck_numeracao_tipo CHECK (tipo IN ('PRODUTO', 'CLIENTE', 'FORNECEDOR'));

-- =====================================================================
-- Passo 7: migracao das marcas em texto (spec 7, item 1).
-- =====================================================================
-- Por empresa, cada valor distinto de lower(btrim(marca)) vira UMA marca na
-- raiz, com a grafia do produto de menor id, aparada ("Golden" e "golden "
-- viram uma so). Vazios sao ignorados.
INSERT INTO marcas (uuid, empresa_id, nome)
SELECT gen_random_uuid(), raiz.empresa_id, raiz.nome
  FROM (SELECT DISTINCT ON (p.empresa_id, lower(btrim(p.marca)))
               p.empresa_id,
               btrim(p.marca) AS nome,
               p.id           AS primeiro_produto_id
          FROM produtos p
         WHERE btrim(p.marca) <> ''
         ORDER BY p.empresa_id, lower(btrim(p.marca)), p.id
       ) AS raiz
 ORDER BY raiz.primeiro_produto_id;

UPDATE produtos p
   SET marca_id = m.id
  FROM marcas m
 WHERE btrim(p.marca) <> ''
   AND m.empresa_id = p.empresa_id
   AND m.parent_id IS NULL
   AND lower(m.nome) = lower(btrim(p.marca));

-- =====================================================================
-- Passo 8: migracao dos fornecedores em texto (spec 7, item 2).
-- =====================================================================
-- Funcao TEMPORARIA (pg_temp), copia exata da V10: o equivalente SQL do
-- TextoDeBusca.normalizar, para as colunas derivadas do fornecedor. Removida
-- logo abaixo.
CREATE FUNCTION pg_temp.normalizar_busca(texto TEXT) RETURNS TEXT
    LANGUAGE sql IMMUTABLE
AS $$
    SELECT btrim(regexp_replace(
               lower(regexp_replace(
                   translate(texto,
                             'ÀÁÂÃÄÅàáâãäåÈÉÊËèéêëÌÍÎÏìíîïÒÓÔÕÖòóôõöÙÚÛÜùúûüÇçÑñÝýÿ',
                             'AAAAAAaaaaaaEEEEeeeeIIIIiiiiOOOOOoooooUUUUuuuuCcNnYyy'),
                   '[̀-ͯ'
                   || '\u0001-\u0008\u000e-\u001f\u007f-\u0084\u0086-\u009f'
                   || '­؀-؅؜۝܏࢐࢑࣢᠎'
                   || '​-‏‪-‮⁠-⁤⁦-⁯﻿￹-￻]',
                   '', 'g')),
               '[\s\u0085   -     　]+', ' ', 'g'))
$$;

-- Por empresa, cada valor distinto de lower(fornecedor) (a V7 ja garante o
-- texto aparado e nao vazio) vira um fornecedor PJ so com a razao social, com a
-- grafia do produto de menor id, numerado por ordem de nome.
INSERT INTO fornecedores (uuid, empresa_id, numero, tipo_pessoa, razao_social, busca_normalizada, nome_normalizado)
SELECT gen_random_uuid(),
       distinto.empresa_id,
       row_number() OVER (PARTITION BY distinto.empresa_id
                          ORDER BY pg_temp.normalizar_busca(distinto.nome), distinto.primeiro_produto_id),
       'PJ',
       distinto.nome,
       pg_temp.normalizar_busca(distinto.nome),
       pg_temp.normalizar_busca(distinto.nome)
  FROM (SELECT DISTINCT ON (p.empresa_id, lower(p.fornecedor))
               p.empresa_id,
               p.fornecedor AS nome,
               p.id         AS primeiro_produto_id
          FROM produtos p
         WHERE p.fornecedor IS NOT NULL
         ORDER BY p.empresa_id, lower(p.fornecedor), p.id
       ) AS distinto;

DROP FUNCTION pg_temp.normalizar_busca(TEXT);

-- Cada produto passa a ter o seu fornecedor na lista e como o da ultima compra.
INSERT INTO produto_fornecedores (empresa_id, produto_id, fornecedor_id)
SELECT p.empresa_id, p.id, f.id
  FROM produtos p
  JOIN fornecedores f
    ON f.empresa_id = p.empresa_id
   AND lower(f.razao_social) = lower(p.fornecedor)
 WHERE p.fornecedor IS NOT NULL;

UPDATE produtos p
   SET fornecedor_ultima_compra_id = pf.fornecedor_id
  FROM produto_fornecedores pf
 WHERE pf.empresa_id = p.empresa_id
   AND pf.produto_id = p.id;

-- =====================================================================
-- Passo 9: o fornecedor da ultima compra tem de estar na lista do produto.
-- =====================================================================
ALTER TABLE produtos
    ADD CONSTRAINT fk_produto_fornecedor_ultima_compra
        FOREIGN KEY (empresa_id, id, fornecedor_ultima_compra_id)
        REFERENCES produto_fornecedores (empresa_id, produto_id, fornecedor_id);

CREATE INDEX idx_produto_fornecedor_ultima_compra ON produtos (fornecedor_ultima_compra_id);

-- =====================================================================
-- Passo 10: conferencia (spec 7, item 3): todo produto que tinha texto ficou
-- ligado. Se falhar, a migration inteira e desfeita.
-- =====================================================================
DO $$
DECLARE
    sem_marca      BIGINT;
    sem_fornecedor BIGINT;
BEGIN
    SELECT count(*) INTO sem_marca
      FROM produtos
     WHERE btrim(marca) <> ''
       AND marca_id IS NULL;

    SELECT count(*) INTO sem_fornecedor
      FROM produtos p
     WHERE p.fornecedor IS NOT NULL
       AND (p.fornecedor_ultima_compra_id IS NULL
            OR NOT EXISTS (SELECT 1
                             FROM produto_fornecedores pf
                             JOIN fornecedores f ON f.empresa_id = pf.empresa_id AND f.id = pf.fornecedor_id
                            WHERE pf.empresa_id = p.empresa_id
                              AND pf.produto_id = p.id
                              AND lower(f.razao_social) = lower(p.fornecedor)));

    IF sem_marca > 0 OR sem_fornecedor > 0 THEN
        RAISE EXCEPTION 'V14: % produto(s) ficaram sem a marca e % sem o fornecedor do texto.',
            sem_marca, sem_fornecedor;
    END IF;
END
$$;

-- =====================================================================
-- Passo 11: remocao das colunas de texto (spec 7, item 4).
-- =====================================================================
ALTER TABLE produtos
    DROP CONSTRAINT ck_produto_fornecedor_valido,
    DROP COLUMN marca,
    DROP COLUMN fornecedor;

-- =====================================================================
-- Passo 12: numeracoes com o maior numero de FORNECEDOR por empresa (spec 7, item 5).
-- =====================================================================
INSERT INTO numeracoes (empresa_id, tipo, ultimo_numero)
SELECT empresa_id, 'FORNECEDOR', max(numero)
  FROM fornecedores
 GROUP BY empresa_id;
