-- V19: devolucao de item (etapa 12, fatia 3; docs/modules/estoque.md, secao
-- 6.2, DEC-045 e DEC-046) -- devolucoes e itens imutaveis; reembolso no caixa
-- de quem devolve, pela forma original; entrada de estoque por item (e a
-- saida do avariado); venda com devolucao nao e cancelada.
--
-- Migration aditiva (V1-V18 intactas, DEC-020). As constraints trocadas aqui
-- (FK e unico da venda no caixa, CHECKs do estoque e da contagem) so ficam
-- mais permissivas ou ganham um caso novo: os dados existentes continuam
-- validos.
--
-- Convencoes (as da V17):
--  * PK BIGINT identity mais uuid publico (DEC-015, DEC-019), gerado pela
--    aplicacao (sem DEFAULT).
--  * Isolamento por empresa (DEC-016) com FKs COMPOSTAS (empresa_id, ...).
--  * Dinheiro em NUMERIC(12,2) e quantidades em NUMERIC(12,3).
--  * Horarios TIMESTAMPTZ preenchidos pela aplicacao com o Clock.
--  * Os gatilhos usam o SQLSTATE 23000 (integrity_constraint_violation).
--  * Travas (DT-032), nesta ordem: a sessao de quem devolve (FOR SHARE), a
--    venda (FOR NO KEY UPDATE: serializa as devolucoes da mesma venda e o
--    cancelamento), os itens da venda pela ordem (FOR NO KEY UPDATE) e os
--    saldos dos produtos em ordem de id.

-- =====================================================================
-- Passo 1: devolucoes.
-- =====================================================================
CREATE TABLE devolucoes (
    id                 BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid               UUID          NOT NULL,
    empresa_id         BIGINT        NOT NULL,
    venda_id           BIGINT        NOT NULL,
    -- A sessao de quem devolve (o reembolso sai dela), nao a da venda.
    sessao_caixa_id    BIGINT        NOT NULL,
    usuario_id         BIGINT        NOT NULL,
    motivo             VARCHAR(200)  NOT NULL,
    -- Soma dos itens; pode ser zero quando os itens devolvidos tinham liquido zero.
    valor              NUMERIC(12,2) NOT NULL,
    chave_idempotencia UUID          NOT NULL,
    criada_em          TIMESTAMPTZ   NOT NULL,
    CONSTRAINT uq_devolucao_uuid UNIQUE (uuid),
    CONSTRAINT uq_devolucao_empresa_id UNIQUE (empresa_id, id),
    -- Alvo das FKs dos itens e do reembolso: os dois sao da mesma venda.
    CONSTRAINT uq_devolucao_empresa_venda_id UNIQUE (empresa_id, venda_id, id),
    CONSTRAINT uq_devolucao_chave UNIQUE (empresa_id, chave_idempotencia),
    CONSTRAINT fk_devolucao_venda FOREIGN KEY (empresa_id, venda_id)
        REFERENCES vendas (empresa_id, id) ON DELETE RESTRICT,
    -- A sessao e da empresa e foi aberta por quem devolve.
    CONSTRAINT fk_devolucao_sessao_de_quem_devolve FOREIGN KEY (empresa_id, sessao_caixa_id, usuario_id)
        REFERENCES sessoes_caixa (empresa_id, id, aberta_por) ON DELETE RESTRICT,
    CONSTRAINT fk_devolucao_usuario FOREIGN KEY (empresa_id, usuario_id)
        REFERENCES usuario (empresa_id, id),
    CONSTRAINT ck_devolucao_motivo CHECK (motivo = btrim(motivo) AND motivo <> ''),
    CONSTRAINT ck_devolucao_valor CHECK (valor >= 0)
);

-- Devolucoes da venda (o disponivel por linha e por forma) e a FK RESTRICT da venda.
CREATE INDEX ix_devolucao_venda ON devolucoes (empresa_id, venda_id);
-- FK RESTRICT da sessao.
CREATE INDEX ix_devolucao_sessao ON devolucoes (empresa_id, sessao_caixa_id);

-- =====================================================================
-- Passo 2: itens da devolucao.
-- =====================================================================
-- Alvo da FK do item da devolucao: o item e da mesma venda e do mesmo produto.
ALTER TABLE itens_venda
    ADD CONSTRAINT uq_item_venda_empresa_venda_produto_id UNIQUE (empresa_id, venda_id, produto_id, id);

CREATE TABLE itens_devolucao (
    id                 BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id         BIGINT        NOT NULL,
    devolucao_id       BIGINT        NOT NULL,
    -- Repetidos do item para as FKs compostas (mesma venda e mesmo produto).
    venda_id           BIGINT        NOT NULL,
    produto_id         BIGINT        NOT NULL,
    item_venda_id      BIGINT        NOT NULL,
    -- Na unidade da linha da venda (3 CX, 1,250 KG).
    quantidade         NUMERIC(12,3) NOT NULL,
    -- Na unidade de venda do produto: o que volta ao estoque.
    quantidade_estoque NUMERIC(12,3) NOT NULL,
    valor              NUMERIC(12,2) NOT NULL,
    destino            VARCHAR(10)   NOT NULL,
    CONSTRAINT uq_item_devolucao_item UNIQUE (devolucao_id, item_venda_id),
    -- Alvo da FK do movimento de estoque: o movimento e do mesmo produto do item.
    CONSTRAINT uq_item_devolucao_empresa_produto_id UNIQUE (empresa_id, produto_id, id),
    CONSTRAINT fk_item_devolucao_devolucao FOREIGN KEY (empresa_id, venda_id, devolucao_id)
        REFERENCES devolucoes (empresa_id, venda_id, id) ON DELETE RESTRICT,
    CONSTRAINT fk_item_devolucao_item_venda FOREIGN KEY (empresa_id, venda_id, produto_id, item_venda_id)
        REFERENCES itens_venda (empresa_id, venda_id, produto_id, id) ON DELETE RESTRICT,
    CONSTRAINT ck_item_devolucao_quantidade CHECK (quantidade > 0 AND quantidade_estoque > 0),
    CONSTRAINT ck_item_devolucao_valor CHECK (valor >= 0),
    CONSTRAINT ck_item_devolucao_destino CHECK (destino IN ('ESTOQUE', 'AVARIADO'))
);

-- Soma ja devolvida de cada item da venda.
CREATE INDEX ix_item_devolucao_item_venda ON itens_devolucao (empresa_id, item_venda_id);

-- =====================================================================
-- Passo 3: reembolso no caixa (movimento DEVOLUCAO).
-- =====================================================================
ALTER TABLE movimentos_caixa
    ADD COLUMN devolucao_id BIGINT,
    DROP CONSTRAINT ck_movimento_caixa_tipo,
    ADD CONSTRAINT ck_movimento_caixa_tipo CHECK (
        tipo IN ('ABERTURA', 'SUPRIMENTO', 'SANGRIA', 'RECEBIMENTO', 'ESTORNO', 'DEVOLUCAO')),
    DROP CONSTRAINT ck_movimento_caixa_motivo,
    -- O motivo da devolucao fica na propria devolucao.
    ADD CONSTRAINT ck_movimento_caixa_motivo CHECK (
        (tipo IN ('ABERTURA', 'RECEBIMENTO', 'ESTORNO', 'DEVOLUCAO') AND motivo IS NULL)
        OR (tipo IN ('SUPRIMENTO', 'SANGRIA') AND motivo IS NOT NULL AND motivo = btrim(motivo) AND motivo <> '')),
    DROP CONSTRAINT ck_movimento_caixa_da_venda,
    -- Venda: com a venda e sem chave (a idempotencia e a da venda ou a da
    -- devolucao); a devolucao, e so ela, tambem liga a devolucao.
    ADD CONSTRAINT ck_movimento_caixa_da_venda CHECK (
        (tipo NOT IN ('RECEBIMENTO', 'ESTORNO', 'DEVOLUCAO') OR (venda_id IS NOT NULL AND chave_idempotencia IS NULL))
        AND ((tipo = 'DEVOLUCAO') = (devolucao_id IS NOT NULL))),
    -- A devolucao fica na sessao de quem devolve, que pode nao ser a da venda:
    -- a FK so prende a venda a empresa. A mesma sessao do recebimento e do
    -- estorno passa para o gatilho do Passo 6.
    DROP CONSTRAINT fk_movimento_caixa_venda,
    ADD CONSTRAINT fk_movimento_caixa_venda FOREIGN KEY (empresa_id, venda_id)
        REFERENCES vendas (empresa_id, id) ON DELETE RESTRICT,
    -- A devolucao e da mesma venda do movimento. MATCH SIMPLE.
    ADD CONSTRAINT fk_movimento_caixa_devolucao FOREIGN KEY (empresa_id, venda_id, devolucao_id)
        REFERENCES devolucoes (empresa_id, venda_id, id) ON DELETE RESTRICT,
    -- O unico da V17 impediria a segunda devolucao na mesma forma.
    DROP CONSTRAINT uq_movimento_caixa_venda;

-- Um recebimento e um estorno por forma e por venda (como na V17).
CREATE UNIQUE INDEX uq_movimento_caixa_venda
    ON movimentos_caixa (empresa_id, venda_id, tipo, forma)
    WHERE tipo IN ('RECEBIMENTO', 'ESTORNO');

-- Um reembolso por forma em cada devolucao.
CREATE UNIQUE INDEX uq_movimento_caixa_devolucao
    ON movimentos_caixa (empresa_id, devolucao_id, forma)
    WHERE devolucao_id IS NOT NULL;

-- Ja reembolsado da venda por forma.
CREATE INDEX ix_movimento_caixa_venda_devolucao
    ON movimentos_caixa (empresa_id, venda_id, forma)
    WHERE tipo = 'DEVOLUCAO';

-- No debito, no credito e no PIX o estorno e feito na maquininha ou no banco e
-- so registrado aqui: o esperado dessas formas pode ficar negativo na sessao
-- de quem devolve. O contado continua >= 0.
ALTER TABLE contagens_caixa
    DROP CONSTRAINT ck_contagem_caixa_valores,
    ADD CONSTRAINT ck_contagem_caixa_valores CHECK (valor_contado >= 0);

-- =====================================================================
-- Passo 4: estoque da devolucao.
-- =====================================================================
ALTER TABLE movimentos_estoque
    ADD COLUMN item_devolucao_id BIGINT,
    DROP CONSTRAINT ck_movimento_estoque_origem,
    ADD CONSTRAINT ck_movimento_estoque_origem CHECK (origem IN ('AJUSTE_MANUAL', 'CADASTRO', 'VENDA', 'DEVOLUCAO')),
    DROP CONSTRAINT ck_movimento_estoque_motivo,
    ADD CONSTRAINT ck_movimento_estoque_motivo CHECK (motivo IN (
        'COMPRA', 'DEVOLUCAO_CLIENTE', 'PERDA_AVARIA', 'VENCIDO', 'USO_INTERNO', 'DEVOLUCAO_FORNECEDOR',
        'CONTAGEM', 'OUTRO', 'ESTOQUE_INICIAL', 'VENDA', 'CANCELAMENTO_VENDA', 'DEVOLUCAO_VENDA')),
    DROP CONSTRAINT ck_movimento_estoque_motivo_do_tipo,
    ADD CONSTRAINT ck_movimento_estoque_motivo_do_tipo CHECK (
        (tipo <> 'ENTRADA' OR motivo IN ('COMPRA', 'DEVOLUCAO_CLIENTE', 'ESTOQUE_INICIAL', 'CANCELAMENTO_VENDA',
                                         'DEVOLUCAO_VENDA', 'OUTRO'))
        AND (tipo <> 'SAIDA' OR motivo IN ('PERDA_AVARIA', 'VENCIDO', 'USO_INTERNO', 'DEVOLUCAO_FORNECEDOR',
                                           'VENDA', 'OUTRO'))
        AND (tipo <> 'AJUSTE' OR motivo IN ('CONTAGEM', 'OUTRO'))),
    -- O item da devolucao e do mesmo produto (e empresa) do movimento. MATCH SIMPLE.
    ADD CONSTRAINT fk_movimento_estoque_item_devolucao FOREIGN KEY (empresa_id, produto_id, item_devolucao_id)
        REFERENCES itens_devolucao (empresa_id, produto_id, id) ON DELETE RESTRICT,
    -- Uma entrada e (no avariado) uma saida por item da devolucao.
    ADD CONSTRAINT uq_movimento_estoque_item_devolucao UNIQUE (empresa_id, item_devolucao_id, motivo),
    -- A origem DEVOLUCAO so produz a entrada DEVOLUCAO_VENDA e a saida
    -- PERDA_AVARIA do avariado, sempre ligadas ao item da devolucao e sem chave
    -- (a idempotencia e a da devolucao).
    ADD CONSTRAINT ck_movimento_estoque_da_devolucao CHECK (
        (origem = 'DEVOLUCAO') = (item_devolucao_id IS NOT NULL)
        AND (origem <> 'DEVOLUCAO' OR (
            ((tipo = 'ENTRADA' AND motivo = 'DEVOLUCAO_VENDA') OR (tipo = 'SAIDA' AND motivo = 'PERDA_AVARIA'))
            AND chave_idempotencia IS NULL))
        AND (motivo <> 'DEVOLUCAO_VENDA' OR origem = 'DEVOLUCAO')),
    -- O avariado volta o saldo para onde estava, mesmo que negativo: a saida
    -- PERDA_AVARIA da devolucao e a nova excecao.
    DROP CONSTRAINT ck_movimento_estoque_saldo_nao_negativo_fora_da_venda,
    ADD CONSTRAINT ck_movimento_estoque_saldo_nao_negativo_fora_da_venda CHECK (
        saldo_novo >= 0 OR motivo = 'VENDA' OR tipo = 'ENTRADA'
        OR (origem = 'DEVOLUCAO' AND motivo = 'PERDA_AVARIA'));

-- =====================================================================
-- Passo 5: esperado do caixa com a devolucao (subtrai, como o estorno).
-- =====================================================================
CREATE OR REPLACE FUNCTION fn_contagem_caixa_coerente() RETURNS trigger
    LANGUAGE plpgsql AS $$
DECLARE
    situacao VARCHAR(15);
    movimentos INTEGER;
    esperado NUMERIC(12,2);
BEGIN
    IF NEW.forma = 'DINHEIRO' THEN
        RETURN NEW;
    END IF;

    -- FOR NO KEY UPDATE (e nao FOR SHARE): com a sessao travada para escrita,
    -- nenhum movimento novo entra entre esta conferencia e a mudanca de
    -- situacao da sessao.
    SELECT status INTO situacao
    FROM sessoes_caixa
    WHERE empresa_id = NEW.empresa_id AND id = NEW.sessao_caixa_id
    FOR NO KEY UPDATE;

    IF FOUND AND situacao <> 'ABERTA' THEN
        RAISE EXCEPTION 'Contagem por forma só entra em sessão aberta.'
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;

    SELECT count(*), COALESCE(SUM(CASE WHEN tipo IN ('ESTORNO', 'DEVOLUCAO') THEN -valor ELSE valor END), 0)
      INTO movimentos, esperado
    FROM movimentos_caixa
    WHERE empresa_id = NEW.empresa_id AND sessao_caixa_id = NEW.sessao_caixa_id AND forma = NEW.forma;

    IF movimentos = 0 THEN
        RAISE EXCEPTION 'A forma % não teve movimento nesta sessão.', NEW.forma
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;

    IF esperado <> NEW.valor_esperado THEN
        RAISE EXCEPTION 'O esperado da forma % não confere com os movimentos.', NEW.forma
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;

    RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION fn_sessao_caixa_diferenca_por_forma() RETURNS trigger
    LANGUAGE plpgsql AS $$
DECLARE
    tem_diferenca BOOLEAN;
BEGIN
    -- Sessao aberta nao tem contagem; a fechada nao muda (o gatilho da V16 recusa).
    IF NEW.status = 'ABERTA' OR OLD.status = 'FECHADA' THEN
        RETURN NEW;
    END IF;

    IF OLD.status = 'ABERTA' AND EXISTS (
            SELECT 1
            FROM movimentos_caixa m
            WHERE m.empresa_id = NEW.empresa_id AND m.sessao_caixa_id = NEW.id AND m.forma <> 'DINHEIRO'
              AND NOT EXISTS (SELECT 1 FROM contagens_caixa c
                              WHERE c.sessao_caixa_id = m.sessao_caixa_id AND c.forma = m.forma)) THEN
        RAISE EXCEPTION 'Conte todas as formas de pagamento que tiveram movimento antes de fechar o caixa.'
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;

    -- Ao sair de ABERTA, a fotografia confere com os movimentos: o esperado
    -- do dinheiro (sangria, estorno e devolucao subtraem) e o de cada forma
    -- contada (estorno e devolucao subtraem).
    IF OLD.status = 'ABERTA' THEN
        IF NEW.valor_esperado IS DISTINCT FROM (
                SELECT COALESCE(SUM(CASE WHEN m.tipo IN ('SANGRIA', 'ESTORNO', 'DEVOLUCAO') THEN -m.valor
                                         ELSE m.valor END), 0)
                FROM movimentos_caixa m
                WHERE m.empresa_id = NEW.empresa_id AND m.sessao_caixa_id = NEW.id AND m.forma = 'DINHEIRO') THEN
            RAISE EXCEPTION 'O esperado em dinheiro não confere com os movimentos do caixa.'
                USING ERRCODE = 'integrity_constraint_violation';
        END IF;
        IF EXISTS (
                SELECT 1
                FROM contagens_caixa c
                WHERE c.empresa_id = NEW.empresa_id AND c.sessao_caixa_id = NEW.id
                  AND c.valor_esperado <> (
                      SELECT COALESCE(SUM(CASE WHEN m.tipo IN ('ESTORNO', 'DEVOLUCAO') THEN -m.valor
                                               ELSE m.valor END), 0)
                      FROM movimentos_caixa m
                      WHERE m.empresa_id = c.empresa_id AND m.sessao_caixa_id = c.sessao_caixa_id
                        AND m.forma = c.forma)) THEN
            RAISE EXCEPTION 'O esperado de uma forma não confere com os movimentos do caixa.'
                USING ERRCODE = 'integrity_constraint_violation';
        END IF;
    END IF;

    tem_diferenca := COALESCE(NEW.diferenca <> 0, false) OR EXISTS (
        SELECT 1 FROM contagens_caixa c
        WHERE c.empresa_id = NEW.empresa_id AND c.sessao_caixa_id = NEW.id AND c.diferenca <> 0);

    IF NEW.status = 'EM_CONFERENCIA' AND NOT tem_diferenca THEN
        RAISE EXCEPTION 'Caixa em conferência exige diferença em alguma forma.'
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;

    IF NEW.status = 'FECHADA' AND tem_diferenca
            AND (NEW.justificativa IS NULL OR btrim(NEW.justificativa) = '') THEN
        RAISE EXCEPTION 'Caixa fechado com diferença exige a justificativa.'
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;

    IF OLD.status = 'ABERTA' AND NEW.status = 'FECHADA' AND NEW.fechamento_cego AND tem_diferenca THEN
        RAISE EXCEPTION 'No fechamento cego, a contagem com diferença passa pela conferência.'
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;

    RETURN NEW;
END;
$$;

