-- Devolucao e item da devolucao sao imutaveis.
CREATE FUNCTION fn_devolucao_imutavel() RETURNS trigger
    LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'Devolução não pode ser alterada nem excluída.'
        USING ERRCODE = 'integrity_constraint_violation';
END;
$$;

CREATE TRIGGER tg_devolucao_imutavel
    BEFORE UPDATE OR DELETE ON devolucoes
    FOR EACH ROW EXECUTE FUNCTION fn_devolucao_imutavel();

CREATE TRIGGER tg_item_devolucao_imutavel
    BEFORE UPDATE OR DELETE ON itens_devolucao
    FOR EACH ROW EXECUTE FUNCTION fn_devolucao_imutavel();

-- Devolucao so de venda CONCLUIDA, na sessao ABERTA de quem devolve. O FOR NO
-- KEY UPDATE na venda espera um cancelamento ou outra devolucao da mesma venda
-- em andamento (e eles esperam esta): o reembolsado por forma e o devolvido
-- por item sao sempre lidos depois do commit da anterior. Venda ou sessao de
-- outra empresa ficam para as FKs.
CREATE FUNCTION fn_devolucao_coerente() RETURNS trigger
    LANGUAGE plpgsql AS $$
DECLARE
    situacao_da_venda VARCHAR(10);
    situacao_da_sessao VARCHAR(15);
BEGIN
    SELECT status INTO situacao_da_sessao
    FROM sessoes_caixa
    WHERE empresa_id = NEW.empresa_id AND id = NEW.sessao_caixa_id
    FOR SHARE;

    IF FOUND AND situacao_da_sessao <> 'ABERTA' THEN
        RAISE EXCEPTION 'Devolução só entra em sessão aberta.'
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;

    SELECT status INTO situacao_da_venda
    FROM vendas
    WHERE empresa_id = NEW.empresa_id AND id = NEW.venda_id
    FOR NO KEY UPDATE;

    IF FOUND AND situacao_da_venda <> 'CONCLUIDA' THEN
        RAISE EXCEPTION 'Devolução só de venda concluída.'
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER tg_devolucao_coerente
    BEFORE INSERT ON devolucoes
    FOR EACH ROW EXECUTE FUNCTION fn_devolucao_coerente();

-- Venda com devolucao nao e cancelada (estoque.md 6.2, regra 7).
CREATE FUNCTION fn_venda_com_devolucao_nao_cancela() RETURNS trigger
    LANGUAGE plpgsql AS $$
BEGIN
    IF EXISTS (SELECT 1 FROM devolucoes WHERE empresa_id = NEW.empresa_id AND venda_id = NEW.id) THEN
        RAISE EXCEPTION 'Venda com devolução não pode ser cancelada.'
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER tg_venda_com_devolucao_nao_cancela
    BEFORE UPDATE ON vendas
    FOR EACH ROW
    WHEN (OLD.status = 'CONCLUIDA' AND NEW.status = 'CANCELADA')
    EXECUTE FUNCTION fn_venda_com_devolucao_nao_cancela();

-- Item da devolucao preso ao item da venda: a quantidade de estoque segue a
-- embalagem da linha; a soma devolvida (quantidade e valor) nunca passa do
-- vendido; e a devolucao que zera a linha leva o resto do liquido (regra 3).
-- O FOR NO KEY UPDATE no item serializa duas devolucoes da mesma linha.
CREATE FUNCTION fn_item_devolucao_coerente() RETURNS trigger
    LANGUAGE plpgsql AS $$
DECLARE
    item itens_venda%ROWTYPE;
    devolvida NUMERIC(12,3);
    valor_devolvido NUMERIC(12,2);
BEGIN
    SELECT * INTO item
    FROM itens_venda
    WHERE empresa_id = NEW.empresa_id AND id = NEW.item_venda_id
    FOR NO KEY UPDATE;

    IF NOT FOUND THEN
        RETURN NEW;
    END IF;

    IF NEW.quantidade_estoque <> NEW.quantidade * COALESCE(item.embalagem_quantidade, 1) THEN
        RAISE EXCEPTION 'Quantidade de estoque da devolução diferente da embalagem do item.'
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;

    SELECT COALESCE(SUM(quantidade), 0), COALESCE(SUM(valor), 0)
      INTO devolvida, valor_devolvido
    FROM itens_devolucao
    WHERE empresa_id = NEW.empresa_id AND item_venda_id = NEW.item_venda_id;

    IF devolvida + NEW.quantidade > item.quantidade THEN
        RAISE EXCEPTION 'Devolução maior que a quantidade vendida no item.'
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;

    IF valor_devolvido + NEW.valor > item.valor_liquido THEN
        RAISE EXCEPTION 'Devolução maior que o valor líquido do item.'
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;

    IF devolvida + NEW.quantidade = item.quantidade AND valor_devolvido + NEW.valor <> item.valor_liquido THEN
        RAISE EXCEPTION 'A devolução que zera o item leva o resto do valor líquido.'
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER tg_item_devolucao_coerente
    BEFORE INSERT ON itens_devolucao
    FOR EACH ROW EXECUTE FUNCTION fn_item_devolucao_coerente();

-- Recebimento e estorno continuam na sessao da venda (a FK da V17 garantia
-- isso; a nova so prende a venda a empresa).
CREATE FUNCTION fn_movimento_caixa_na_sessao_da_venda() RETURNS trigger
    LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.tipo IN ('RECEBIMENTO', 'ESTORNO') AND NEW.venda_id IS NOT NULL AND NOT EXISTS (
            SELECT 1 FROM vendas
            WHERE empresa_id = NEW.empresa_id AND id = NEW.venda_id AND sessao_caixa_id = NEW.sessao_caixa_id) THEN
        RAISE EXCEPTION 'Recebimento e estorno ficam na sessão da venda.'
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER tg_movimento_caixa_na_sessao_da_venda
    BEFORE INSERT ON movimentos_caixa
    FOR EACH ROW EXECUTE FUNCTION fn_movimento_caixa_na_sessao_da_venda();

-- Reembolso preso a devolucao e ao recebido: na sessao da devolucao, numa
-- forma que a venda recebeu, e a soma reembolsada na forma (todas as
-- devolucoes da venda) nunca passa do recebido (no dinheiro, sem o troco).
CREATE FUNCTION fn_movimento_caixa_reembolso_da_devolucao() RETURNS trigger
    LANGUAGE plpgsql AS $$
DECLARE
    recebido NUMERIC(12,2);
    reembolsado NUMERIC(12,2);
BEGIN
    IF NEW.tipo <> 'DEVOLUCAO' OR NEW.devolucao_id IS NULL THEN
        RETURN NEW;
    END IF;

    IF NOT EXISTS (
            SELECT 1 FROM devolucoes
            WHERE empresa_id = NEW.empresa_id AND id = NEW.devolucao_id AND sessao_caixa_id = NEW.sessao_caixa_id) THEN
        RAISE EXCEPTION 'Reembolso fora da sessão da devolução.'
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;

    SELECT p.valor - CASE WHEN p.forma = 'DINHEIRO' THEN v.troco ELSE 0 END INTO recebido
    FROM pagamentos_venda p
    JOIN vendas v ON v.id = p.venda_id
    WHERE v.empresa_id = NEW.empresa_id AND v.id = NEW.venda_id AND p.forma = NEW.forma;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Reembolso numa forma que a venda não recebeu.'
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;

    SELECT COALESCE(SUM(valor), 0) INTO reembolsado
    FROM movimentos_caixa
    WHERE empresa_id = NEW.empresa_id AND venda_id = NEW.venda_id AND tipo = 'DEVOLUCAO' AND forma = NEW.forma;

    IF reembolsado + NEW.valor > recebido THEN
        RAISE EXCEPTION 'Reembolso maior que o recebido da venda na forma.'
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER tg_movimento_caixa_reembolso_da_devolucao
    BEFORE INSERT ON movimentos_caixa
    FOR EACH ROW EXECUTE FUNCTION fn_movimento_caixa_reembolso_da_devolucao();

-- Estoque da devolucao preso ao item: a entrada devolve exatamente a
-- quantidade de estoque do item da devolucao, e so de item que baixou estoque
-- na venda; a saida do avariado tira exatamente o que entrou.
CREATE FUNCTION fn_movimento_estoque_da_devolucao() RETURNS trigger
    LANGUAGE plpgsql AS $$
DECLARE
    item itens_devolucao%ROWTYPE;
BEGIN
    IF NEW.origem <> 'DEVOLUCAO' OR NEW.item_devolucao_id IS NULL THEN
        RETURN NEW;
    END IF;

    SELECT * INTO item
    FROM itens_devolucao
    WHERE empresa_id = NEW.empresa_id AND id = NEW.item_devolucao_id;

    IF NOT FOUND THEN
        RETURN NEW;
    END IF;

    IF NEW.motivo = 'DEVOLUCAO_VENDA' THEN
        IF NEW.quantidade <> item.quantidade_estoque THEN
            RAISE EXCEPTION 'Entrada da devolução diferente da quantidade de estoque do item.'
                USING ERRCODE = 'integrity_constraint_violation';
        END IF;
        IF NOT EXISTS (
                SELECT 1 FROM movimentos_estoque b
                WHERE b.empresa_id = NEW.empresa_id AND b.item_venda_id = item.item_venda_id AND b.motivo = 'VENDA') THEN
            RAISE EXCEPTION 'Entrada de devolução de um item que não baixou estoque na venda.'
                USING ERRCODE = 'integrity_constraint_violation';
        END IF;
    ELSIF NEW.motivo = 'PERDA_AVARIA' THEN
        IF item.destino <> 'AVARIADO' OR NOT EXISTS (
                SELECT 1 FROM movimentos_estoque e
                WHERE e.empresa_id = NEW.empresa_id AND e.item_devolucao_id = NEW.item_devolucao_id
                  AND e.motivo = 'DEVOLUCAO_VENDA' AND e.quantidade = -NEW.quantidade) THEN
            RAISE EXCEPTION 'Saída do avariado sem a entrada da devolução com a mesma quantidade.'
                USING ERRCODE = 'integrity_constraint_violation';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER tg_movimento_estoque_da_devolucao
    BEFORE INSERT ON movimentos_estoque
    FOR EACH ROW EXECUTE FUNCTION fn_movimento_estoque_da_devolucao();

-- Movimento de estoque da venda e da devolucao e imutavel. Os outros
-- continuam como na V9.
CREATE OR REPLACE FUNCTION fn_movimento_estoque_da_venda_imutavel() RETURNS trigger
    LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.origem = 'VENDA' THEN
        RAISE EXCEPTION 'Movimento de estoque da venda não pode ser alterado nem excluído.'
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;
    IF OLD.origem = 'DEVOLUCAO' THEN
        RAISE EXCEPTION 'Movimento de estoque da devolução não pode ser alterado nem excluído.'
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;
    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END;
$$;

-- Devolucao completa no commit (constraint triggers deferidas, como a venda
-- coerente da V17): a devolucao, os itens, os reembolsos e os movimentos de
-- estoque sao gravados em comandos separados, e um item ou reembolso gravado
-- depois, noutra transacao, confere a devolucao de novo. Ao menos um item;
-- soma dos itens = valor; soma dos reembolsos = valor; todo item que baixou
-- estoque na venda tem a entrada, e o avariado tambem a saida.
CREATE FUNCTION fn_devolucao_completa() RETURNS trigger
    LANGUAGE plpgsql AS $$
DECLARE
    devolucao devolucoes%ROWTYPE;
    alvo BIGINT;
    soma_dos_itens NUMERIC(12,2);
    itens INTEGER;
BEGIN
    IF TG_TABLE_NAME = 'devolucoes' THEN
        alvo := NEW.id;
    ELSE
        alvo := NEW.devolucao_id;
    END IF;

    SELECT * INTO devolucao FROM devolucoes WHERE empresa_id = NEW.empresa_id AND id = alvo;
    IF NOT FOUND THEN
        RETURN NULL;
    END IF;

    SELECT count(*), COALESCE(SUM(valor), 0) INTO itens, soma_dos_itens
    FROM itens_devolucao
    WHERE empresa_id = devolucao.empresa_id AND devolucao_id = devolucao.id;

    IF itens = 0 THEN
        RAISE EXCEPTION 'Devolução sem itens.'
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;

    IF soma_dos_itens <> devolucao.valor THEN
        RAISE EXCEPTION 'O valor da devolução não confere com os itens.'
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;

    IF devolucao.valor <> (
            SELECT COALESCE(SUM(valor), 0) FROM movimentos_caixa
            WHERE empresa_id = devolucao.empresa_id AND devolucao_id = devolucao.id) THEN
        RAISE EXCEPTION 'Os reembolsos não somam o valor da devolução.'
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;

    IF EXISTS (
            SELECT 1
            FROM itens_devolucao d
            WHERE d.empresa_id = devolucao.empresa_id AND d.devolucao_id = devolucao.id
              AND EXISTS (SELECT 1 FROM movimentos_estoque b
                          WHERE b.empresa_id = d.empresa_id AND b.item_venda_id = d.item_venda_id
                            AND b.motivo = 'VENDA')
              AND (NOT EXISTS (SELECT 1 FROM movimentos_estoque e
                               WHERE e.empresa_id = d.empresa_id AND e.item_devolucao_id = d.id
                                 AND e.motivo = 'DEVOLUCAO_VENDA')
                   OR (d.destino = 'AVARIADO' AND NOT EXISTS (
                           SELECT 1 FROM movimentos_estoque s
                           WHERE s.empresa_id = d.empresa_id AND s.item_devolucao_id = d.id
                             AND s.motivo = 'PERDA_AVARIA')))) THEN
        RAISE EXCEPTION 'Devolução sem o movimento de estoque de todos os itens que baixaram estoque.'
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;

    RETURN NULL;
END;
$$;

CREATE CONSTRAINT TRIGGER tg_devolucao_completa
    AFTER INSERT ON devolucoes
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION fn_devolucao_completa();

CREATE CONSTRAINT TRIGGER tg_item_devolucao_completa
    AFTER INSERT ON itens_devolucao
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION fn_devolucao_completa();

CREATE CONSTRAINT TRIGGER tg_reembolso_devolucao_completa
    AFTER INSERT ON movimentos_caixa
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW
    WHEN (NEW.devolucao_id IS NOT NULL)
    EXECUTE FUNCTION fn_devolucao_completa();
