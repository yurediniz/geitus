-- V17: PDV (etapa 11) -- vendas, itens e pagamentos imutaveis; caixa por forma
-- de pagamento (recebimento, estorno e contagem por forma); estoque por venda
-- (baixa, estorno e saldo negativo so por venda); configuracao do PDV.
--
-- Migration aditiva (V1-V16 intactas, DEC-020). Ver docs/modules/pdv.md
-- (secao 4) e DEC-042.
--
-- Convencoes (as da V9 e da V16):
--  * PK BIGINT identity mais uuid publico (DEC-015, DEC-019), gerado pela
--    aplicacao (sem DEFAULT).
--  * Isolamento por empresa (DEC-016) com FKs COMPOSTAS (empresa_id, ...).
--  * Dinheiro em NUMERIC(12,2), quantidades em NUMERIC(12,3) e custo em
--    NUMERIC(12,4).
--  * Horarios TIMESTAMPTZ preenchidos pela aplicacao com o Clock (sem DEFAULT
--    now()).
--  * Os gatilhos usam o SQLSTATE 23000 (integrity_constraint_violation): a
--    aplicacao os recebe como violacao de integridade, nunca como erro 500.
--  * Travas (DT-032): a venda e o cancelamento travam primeiro a sessao de
--    caixa e depois os produtos em ordem de id; os gatilhos abaixo so leem a
--    sessao com FOR SHARE (a propria transacao ja a travou).

-- =====================================================================
-- Passo 1: numeracao das vendas (o Numerador grava o tipo VENDA).
-- =====================================================================
ALTER TABLE numeracoes
    DROP CONSTRAINT ck_numeracao_tipo,
    ADD CONSTRAINT ck_numeracao_tipo CHECK (tipo IN ('PRODUTO', 'CLIENTE', 'FORNECEDOR', 'VENDA'));

-- Alvo da FK composta da venda para o cliente (a V5 nao tem).
ALTER TABLE clientes
    ADD CONSTRAINT uq_cliente_empresa_id UNIQUE (empresa_id, id);

-- Alvo da FK da venda para a sessao do vendedor: a venda entra so no caixa
-- de quem o abriu.
ALTER TABLE sessoes_caixa
    ADD CONSTRAINT uq_sessao_caixa_empresa_id_aberta_por UNIQUE (empresa_id, id, aberta_por);

-- =====================================================================
-- Passo 2: vendas.
-- =====================================================================
CREATE TABLE vendas (
    id                  BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid                UUID          NOT NULL,
    empresa_id          BIGINT        NOT NULL,
    numero              BIGINT        NOT NULL,
    sessao_caixa_id     BIGINT        NOT NULL,
    -- Quem vendeu: sempre quem abriu a sessao (a venda entra no caixa do usuario).
    usuario_id          BIGINT        NOT NULL,
    cliente_id          BIGINT,
    -- Fotografia do nome do cliente na data; NULL sem cliente.
    cliente_nome        VARCHAR(150),
    status              VARCHAR(10)   NOT NULL,
    subtotal            NUMERIC(12,2) NOT NULL,
    desconto_itens      NUMERIC(12,2) NOT NULL,
    desconto_total      NUMERIC(12,2) NOT NULL,
    total               NUMERIC(12,2) NOT NULL,
    troco               NUMERIC(12,2) NOT NULL,
    chave_idempotencia  UUID          NOT NULL,
    concluida_em        TIMESTAMPTZ   NOT NULL,
    cancelada_por       BIGINT,
    cancelada_em        TIMESTAMPTZ,
    motivo_cancelamento VARCHAR(200),
    CONSTRAINT uq_venda_uuid UNIQUE (uuid),
    CONSTRAINT uq_venda_empresa_id UNIQUE (empresa_id, id),
    -- Alvo da FK dos movimentos de caixa: o recebimento e da sessao da venda.
    CONSTRAINT uq_venda_empresa_sessao_id UNIQUE (empresa_id, sessao_caixa_id, id),
    CONSTRAINT uq_venda_numero UNIQUE (empresa_id, numero),
    CONSTRAINT uq_venda_chave UNIQUE (empresa_id, chave_idempotencia),
    -- A sessao e da empresa e foi aberta pelo vendedor (a venda entra no caixa
    -- de quem vende; a regra do dono do cancelamento depende disso).
    CONSTRAINT fk_venda_sessao_do_vendedor FOREIGN KEY (empresa_id, sessao_caixa_id, usuario_id)
        REFERENCES sessoes_caixa (empresa_id, id, aberta_por) ON DELETE RESTRICT,
    -- Usuarios nao sao excluidos fisicamente: RESTRICT (padrao). MATCH SIMPLE:
    -- cliente e cancelamento so conferidos quando preenchidos.
    CONSTRAINT fk_venda_usuario FOREIGN KEY (empresa_id, usuario_id)
        REFERENCES usuario (empresa_id, id),
    CONSTRAINT fk_venda_cliente FOREIGN KEY (empresa_id, cliente_id)
        REFERENCES clientes (empresa_id, id) ON DELETE RESTRICT,
    CONSTRAINT fk_venda_cancelada_por FOREIGN KEY (empresa_id, cancelada_por)
        REFERENCES usuario (empresa_id, id),
    CONSTRAINT ck_venda_numero CHECK (numero > 0),
    CONSTRAINT ck_venda_status CHECK (status IN ('CONCLUIDA', 'CANCELADA')),
    CONSTRAINT ck_venda_valores CHECK (
        total > 0 AND desconto_itens >= 0 AND desconto_total >= 0 AND troco >= 0),
    CONSTRAINT ck_venda_total CHECK (total = subtotal - desconto_itens - desconto_total),
    CONSTRAINT ck_venda_cliente_nome CHECK (
        (cliente_id IS NULL AND cliente_nome IS NULL)
        OR (cliente_id IS NOT NULL AND cliente_nome IS NOT NULL AND btrim(cliente_nome) <> '')),
    -- Coerencia do cancelamento com o status; motivo aparado e nao vazio.
    CONSTRAINT ck_venda_cancelamento CHECK (
        (status = 'CONCLUIDA' AND cancelada_por IS NULL AND cancelada_em IS NULL AND motivo_cancelamento IS NULL)
        OR (status = 'CANCELADA' AND cancelada_por IS NOT NULL AND cancelada_em IS NOT NULL
            AND motivo_cancelamento IS NOT NULL AND motivo_cancelamento = btrim(motivo_cancelamento)
            AND motivo_cancelamento <> ''))
);

-- Vendas do caixa (F8), na ordem da lista (da mais recente, desempate por
-- id); tambem serve a FK RESTRICT da sessao.
CREATE INDEX ix_venda_sessao ON vendas (empresa_id, sessao_caixa_id, concluida_em DESC, id DESC);
-- Consulta por periodo, da mais recente (desempate por id).
CREATE INDEX ix_venda_concluida_em ON vendas (empresa_id, concluida_em DESC, id DESC);
-- FK RESTRICT do cliente.
CREATE INDEX ix_venda_cliente ON vendas (empresa_id, cliente_id) WHERE cliente_id IS NOT NULL;

-- =====================================================================
-- Passo 3: itens da venda (fotografia do que foi vendido).
-- =====================================================================
CREATE TABLE itens_venda (
    id                   BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id           BIGINT        NOT NULL,
    venda_id             BIGINT        NOT NULL,
    -- 1, 2, 3... na ordem do carrinho (ate 300 linhas).
    ordem                SMALLINT      NOT NULL,
    produto_id           BIGINT        NOT NULL,
    produto_nome         VARCHAR(150)  NOT NULL,
    -- O texto lido ("542*3", o EAN ou a etiqueta); NULL na busca por nome.
    codigo_lido          VARCHAR(60),
    unidade_sigla        VARCHAR(20)   NOT NULL,
    -- Retrato da embalagem, sem FK: a embalagem pode sair do produto depois.
    embalagem_rotulo     VARCHAR(60),
    embalagem_quantidade NUMERIC(12,3),
    etiqueta             BOOLEAN       NOT NULL,
    -- Na unidade da linha (3 CX, 1,250 KG).
    quantidade           NUMERIC(12,3) NOT NULL,
    -- Na unidade de venda do produto: o que a linha baixa do estoque.
    quantidade_estoque   NUMERIC(12,3) NOT NULL,
    preco_unitario       NUMERIC(12,2) NOT NULL,
    origem_preco         VARCHAR(12)   NOT NULL,
    valor_bruto          NUMERIC(12,2) NOT NULL,
    desconto_item        NUMERIC(12,2) NOT NULL,
    desconto_rateado     NUMERIC(12,2) NOT NULL,
    valor_liquido        NUMERIC(12,2) NOT NULL,
    -- Custo por unidade de estoque na data; NULL quando o produto nao tem custo.
    custo_unitario       NUMERIC(12,4),
    -- Alvo da FK do movimento de estoque: o movimento e do mesmo produto do item.
    CONSTRAINT uq_item_venda_empresa_produto_id UNIQUE (empresa_id, produto_id, id),
    CONSTRAINT uq_item_venda_ordem UNIQUE (venda_id, ordem),
    CONSTRAINT fk_item_venda_venda FOREIGN KEY (empresa_id, venda_id)
        REFERENCES vendas (empresa_id, id) ON DELETE RESTRICT,
    -- Produto vendido nao e excluido (DT-028).
    CONSTRAINT fk_item_venda_produto FOREIGN KEY (empresa_id, produto_id)
        REFERENCES produtos (empresa_id, id) ON DELETE RESTRICT,
    CONSTRAINT ck_item_venda_ordem CHECK (ordem > 0),
    CONSTRAINT ck_item_venda_quantidade CHECK (quantidade > 0 AND quantidade_estoque > 0),
    CONSTRAINT ck_item_venda_preco CHECK (preco_unitario > 0),
    CONSTRAINT ck_item_venda_origem CHECK (origem_preco IN ('NORMAL', 'PROMOCIONAL', 'ATACADO', 'EMBALAGEM', 'ETIQUETA')),
    CONSTRAINT ck_item_venda_valores CHECK (valor_bruto >= 0 AND desconto_item >= 0 AND desconto_rateado >= 0),
    CONSTRAINT ck_item_venda_liquido CHECK (
        valor_liquido = valor_bruto - desconto_item - desconto_rateado AND valor_liquido >= 0),
    -- Retrato completo ou ausente; a embalagem sempre em quantidade inteira.
    CONSTRAINT ck_item_venda_embalagem CHECK (
        (embalagem_rotulo IS NULL AND embalagem_quantidade IS NULL)
        OR (embalagem_rotulo IS NOT NULL AND embalagem_quantidade IS NOT NULL AND btrim(embalagem_rotulo) <> ''
            AND embalagem_quantidade > 0 AND quantidade = trunc(quantidade) AND NOT etiqueta)),
    CONSTRAINT ck_item_venda_quantidade_estoque CHECK (
        (embalagem_quantidade IS NULL AND quantidade_estoque = quantidade)
        OR (embalagem_quantidade IS NOT NULL AND quantidade_estoque = quantidade * embalagem_quantidade)),
    -- A origem acompanha o tipo da linha.
    CONSTRAINT ck_item_venda_origem_da_linha CHECK (
        (etiqueta = (origem_preco = 'ETIQUETA'))
        AND ((embalagem_rotulo IS NOT NULL) = (origem_preco = 'EMBALAGEM'))),
    CONSTRAINT ck_item_venda_custo CHECK (custo_unitario IS NULL OR custo_unitario >= 0)
);

-- =====================================================================
-- Passo 4: pagamentos da venda (uma linha por forma; o valor informado, o
-- troco fica na venda).
-- =====================================================================
CREATE TABLE pagamentos_venda (
    id         BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id BIGINT        NOT NULL,
    venda_id   BIGINT        NOT NULL,
    forma      VARCHAR(10)   NOT NULL,
    valor      NUMERIC(12,2) NOT NULL,
    CONSTRAINT uq_pagamento_venda_forma UNIQUE (venda_id, forma),
    CONSTRAINT fk_pagamento_venda_venda FOREIGN KEY (empresa_id, venda_id)
        REFERENCES vendas (empresa_id, id) ON DELETE RESTRICT,
    CONSTRAINT ck_pagamento_venda_forma CHECK (forma IN ('DINHEIRO', 'DEBITO', 'CREDITO', 'PIX')),
    CONSTRAINT ck_pagamento_venda_valor CHECK (valor > 0)
);

-- =====================================================================
-- Passo 5: caixa por forma de pagamento.
-- =====================================================================
-- Os movimentos atuais (abertura, suprimento e sangria) sao em dinheiro: o
-- DEFAULT so faz a carga e sai logo depois.
ALTER TABLE movimentos_caixa
    ADD COLUMN forma VARCHAR(10) NOT NULL DEFAULT 'DINHEIRO';

ALTER TABLE movimentos_caixa
    ALTER COLUMN forma DROP DEFAULT,
    ADD COLUMN venda_id BIGINT,
    -- A idempotencia dos movimentos da venda e a da propria venda (DT-032):
    -- recebimento e estorno nao tem chave.
    ALTER COLUMN chave_idempotencia DROP NOT NULL,
    DROP CONSTRAINT ck_movimento_caixa_tipo,
    ADD CONSTRAINT ck_movimento_caixa_tipo CHECK (
        tipo IN ('ABERTURA', 'SUPRIMENTO', 'SANGRIA', 'RECEBIMENTO', 'ESTORNO')),
    ADD CONSTRAINT ck_movimento_caixa_forma CHECK (forma IN ('DINHEIRO', 'DEBITO', 'CREDITO', 'PIX')),
    -- O motivo da V16 era exigido em todo tipo que nao fosse a abertura.
    DROP CONSTRAINT ck_movimento_caixa_motivo,
    ADD CONSTRAINT ck_movimento_caixa_motivo CHECK (
        (tipo IN ('ABERTURA', 'RECEBIMENTO', 'ESTORNO') AND motivo IS NULL)
        OR (tipo IN ('SUPRIMENTO', 'SANGRIA') AND motivo IS NOT NULL AND motivo = btrim(motivo) AND motivo <> '')),
    -- Gaveta: sempre dinheiro, sem venda e com a chave da tela.
    ADD CONSTRAINT ck_movimento_caixa_da_gaveta CHECK (
        tipo NOT IN ('ABERTURA', 'SUPRIMENTO', 'SANGRIA')
        OR (forma = 'DINHEIRO' AND venda_id IS NULL AND chave_idempotencia IS NOT NULL)),
    -- Venda: com a venda e sem chave (o valor > 0 vem do ck_movimento_caixa_valor).
    ADD CONSTRAINT ck_movimento_caixa_da_venda CHECK (
        tipo NOT IN ('RECEBIMENTO', 'ESTORNO') OR (venda_id IS NOT NULL AND chave_idempotencia IS NULL)),
    -- A venda e da mesma sessao (e empresa) do movimento. MATCH SIMPLE: so
    -- conferida com a venda preenchida.
    ADD CONSTRAINT fk_movimento_caixa_venda FOREIGN KEY (empresa_id, sessao_caixa_id, venda_id)
        REFERENCES vendas (empresa_id, sessao_caixa_id, id) ON DELETE RESTRICT,
    -- Um recebimento e um estorno por forma e por venda. NULLs nao conflitam:
    -- os movimentos da gaveta ficam de fora.
    ADD CONSTRAINT uq_movimento_caixa_venda UNIQUE (empresa_id, venda_id, tipo, forma);

-- Contagem das formas que nao sao dinheiro (o dinheiro continua nas colunas
-- da propria sessao). Gravada junto com a contagem e imutavel.
CREATE TABLE contagens_caixa (
    id              BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id      BIGINT        NOT NULL,
    sessao_caixa_id BIGINT        NOT NULL,
    forma           VARCHAR(10)   NOT NULL,
    valor_esperado  NUMERIC(12,2) NOT NULL,
    valor_contado   NUMERIC(12,2) NOT NULL,
    diferenca       NUMERIC(12,2) NOT NULL,
    CONSTRAINT uq_contagem_caixa_forma UNIQUE (sessao_caixa_id, forma),
    CONSTRAINT fk_contagem_caixa_sessao FOREIGN KEY (empresa_id, sessao_caixa_id)
        REFERENCES sessoes_caixa (empresa_id, id) ON DELETE RESTRICT,
    CONSTRAINT ck_contagem_caixa_forma CHECK (forma IN ('DEBITO', 'CREDITO', 'PIX')),
    CONSTRAINT ck_contagem_caixa_valores CHECK (valor_esperado >= 0 AND valor_contado >= 0),
    CONSTRAINT ck_contagem_caixa_diferenca CHECK (diferenca = valor_contado - valor_esperado)
);

-- A regra "EM_CONFERENCIA exige diferenca" e a da justificativa passam a
-- considerar qualquer forma: saem dos CHECKs da sessao (que so veem o
-- dinheiro) e vao para o gatilho do Passo 8.
ALTER TABLE sessoes_caixa
    DROP CONSTRAINT ck_sessao_caixa_em_conferencia,
    ADD CONSTRAINT ck_sessao_caixa_em_conferencia CHECK (
        status <> 'EM_CONFERENCIA' OR (
            fechamento_cego IS NOT NULL AND valor_esperado IS NOT NULL AND valor_contado IS NOT NULL
            AND diferenca IS NOT NULL AND contada_por IS NOT NULL AND contada_em IS NOT NULL
            AND justificativa IS NULL AND fechada_por IS NULL AND fechada_em IS NULL)),
    DROP CONSTRAINT ck_sessao_caixa_justificativa;

-- =====================================================================
-- Passo 6: estoque por venda.
-- =====================================================================
ALTER TABLE movimentos_estoque
    ADD COLUMN item_venda_id BIGINT,
    DROP CONSTRAINT ck_movimento_estoque_motivo,
    ADD CONSTRAINT ck_movimento_estoque_motivo CHECK (motivo IN (
        'COMPRA', 'DEVOLUCAO_CLIENTE', 'PERDA_AVARIA', 'VENCIDO', 'USO_INTERNO', 'DEVOLUCAO_FORNECEDOR',
        'CONTAGEM', 'OUTRO', 'ESTOQUE_INICIAL', 'VENDA', 'CANCELAMENTO_VENDA')),
    DROP CONSTRAINT ck_movimento_estoque_motivo_do_tipo,
    ADD CONSTRAINT ck_movimento_estoque_motivo_do_tipo CHECK (
        (tipo <> 'ENTRADA' OR motivo IN ('COMPRA', 'DEVOLUCAO_CLIENTE', 'ESTOQUE_INICIAL', 'CANCELAMENTO_VENDA',
                                         'OUTRO'))
        AND (tipo <> 'SAIDA' OR motivo IN ('PERDA_AVARIA', 'VENCIDO', 'USO_INTERNO', 'DEVOLUCAO_FORNECEDOR',
                                           'VENDA', 'OUTRO'))
        AND (tipo <> 'AJUSTE' OR motivo IN ('CONTAGEM', 'OUTRO'))),
    -- O item e do mesmo produto (e empresa) do movimento. MATCH SIMPLE.
    ADD CONSTRAINT fk_movimento_estoque_item_venda FOREIGN KEY (empresa_id, produto_id, item_venda_id)
        REFERENCES itens_venda (empresa_id, produto_id, id) ON DELETE RESTRICT,
    -- Uma baixa e um estorno por item.
    ADD CONSTRAINT uq_movimento_estoque_item_venda UNIQUE (empresa_id, item_venda_id, motivo),
    -- A origem VENDA so produz a baixa e o estorno da venda, sempre ligados ao
    -- item e sem chave (a idempotencia e a da venda, DT-032).
    ADD CONSTRAINT ck_movimento_estoque_da_venda CHECK (
        (origem = 'VENDA') = (item_venda_id IS NOT NULL)
        AND (origem <> 'VENDA' OR (motivo IN ('VENDA', 'CANCELAMENTO_VENDA') AND chave_idempotencia IS NULL))
        AND (motivo NOT IN ('VENDA', 'CANCELAMENTO_VENDA') OR origem = 'VENDA'));

-- Saldo negativo so por venda (com "Vender sem estoque" ligada, conferido no
-- service). Saem a regra do saldo >= 0 da linha de saldo e a dos dois saldos
-- do movimento; entra a regra no movimento: o saldo novo so fica negativo
-- numa saida por venda ou numa entrada (que nunca piora o saldo: uma compra ou
-- o estorno de outra venda enquanto o saldo ainda esta negativo).
ALTER TABLE estoque_saldos
    DROP CONSTRAINT ck_estoque_saldo_nao_negativo;

ALTER TABLE movimentos_estoque
    DROP CONSTRAINT ck_movimento_estoque_saldos,
    ADD CONSTRAINT ck_movimento_estoque_saldo_nao_negativo_fora_da_venda CHECK (
        saldo_novo >= 0 OR motivo = 'VENDA' OR tipo = 'ENTRADA');

-- =====================================================================
-- Passo 7: configuracao do PDV (uma linha por empresa; sem linha vale o
-- padrao: vender sem estoque ligado e desconto maximo do operador de 10%).
-- =====================================================================
CREATE TABLE configuracoes_pdv (
    empresa_id               BIGINT       PRIMARY KEY,
    vender_sem_estoque       BOOLEAN      NOT NULL DEFAULT true,
    desconto_maximo_operador NUMERIC(5,2) NOT NULL DEFAULT 10.00,
    atualizado_por           BIGINT       NOT NULL,
    atualizado_em            TIMESTAMPTZ  NOT NULL,
    CONSTRAINT fk_configuracao_pdv_empresa FOREIGN KEY (empresa_id) REFERENCES empresa (id),
    CONSTRAINT fk_configuracao_pdv_usuario FOREIGN KEY (empresa_id, atualizado_por)
        REFERENCES usuario (empresa_id, id),
    CONSTRAINT ck_configuracao_pdv_desconto CHECK (desconto_maximo_operador BETWEEN 0 AND 100)
);

-- =====================================================================
-- Passo 8: gatilhos.
-- =====================================================================

-- Venda: nasce CONCLUIDA, numa sessao ABERTA; nunca e excluida; so muda de
-- CONCLUIDA para CANCELADA, com o preenchimento do cancelamento (coerencia no
-- ck_venda_cancelamento), e o cancelamento tambem exige a sessao ABERTA.
CREATE FUNCTION fn_venda_protegida() RETURNS trigger
    LANGUAGE plpgsql AS $$
DECLARE
    situacao VARCHAR(15);
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'Venda não pode ser excluída.'
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;

    IF TG_OP = 'INSERT' THEN
        IF NEW.status <> 'CONCLUIDA' THEN
            RAISE EXCEPTION 'Venda nasce concluída.'
                USING ERRCODE = 'integrity_constraint_violation';
        END IF;
    ELSE
        IF OLD.status <> 'CONCLUIDA' THEN
            RAISE EXCEPTION 'Venda cancelada não pode ser alterada.'
                USING ERRCODE = 'integrity_constraint_violation';
        END IF;
        IF NEW.status <> 'CANCELADA'
                OR (NEW.id, NEW.uuid, NEW.empresa_id, NEW.numero, NEW.sessao_caixa_id, NEW.usuario_id,
                    NEW.cliente_id, NEW.cliente_nome, NEW.subtotal, NEW.desconto_itens, NEW.desconto_total,
                    NEW.total, NEW.troco, NEW.chave_idempotencia, NEW.concluida_em)
                   IS DISTINCT FROM
                   (OLD.id, OLD.uuid, OLD.empresa_id, OLD.numero, OLD.sessao_caixa_id, OLD.usuario_id,
                    OLD.cliente_id, OLD.cliente_nome, OLD.subtotal, OLD.desconto_itens, OLD.desconto_total,
                    OLD.total, OLD.troco, OLD.chave_idempotencia, OLD.concluida_em) THEN
            RAISE EXCEPTION 'Venda só pode ser cancelada; os dados da venda não mudam.'
                USING ERRCODE = 'integrity_constraint_violation';
        END IF;
    END IF;

    -- Sessao inexistente na empresa fica para a FK fk_venda_sessao_do_vendedor recusar.
    SELECT status INTO situacao
    FROM sessoes_caixa
    WHERE empresa_id = NEW.empresa_id AND id = NEW.sessao_caixa_id
    FOR SHARE;

    IF FOUND AND situacao <> 'ABERTA' THEN
        RAISE EXCEPTION 'Venda só entra (e só é cancelada) em sessão aberta.'
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER tg_venda_protegida
    BEFORE INSERT OR UPDATE OR DELETE ON vendas
    FOR EACH ROW EXECUTE FUNCTION fn_venda_protegida();

