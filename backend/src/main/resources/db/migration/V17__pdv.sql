-- Contagem por forma: so em sessao ABERTA (gravada antes de a sessao mudar de
-- situacao, na mesma transacao), so de forma que teve movimento na sessao e
-- com o esperado igual a soma dos movimentos dela (recebimentos - estornos).
-- O dinheiro fica para o ck_contagem_caixa_forma recusar.
CREATE FUNCTION fn_contagem_caixa_coerente() RETURNS trigger
    LANGUAGE plpgsql AS $$
DECLARE
    situacao VARCHAR(15);
    movimentos INTEGER;
    esperado NUMERIC(12,2);
BEGIN
    IF NEW.forma = 'DINHEIRO' THEN
        RETURN NEW;
    END IF;

    -- FOR NO KEY UPDATE (e nao FOR SHARE): com a sessao travada para escrita,
    -- nenhum movimento novo entra entre esta conferencia e a mudanca de
    -- situacao da sessao.
    SELECT status INTO situacao
    FROM sessoes_caixa
    WHERE empresa_id = NEW.empresa_id AND id = NEW.sessao_caixa_id
    FOR NO KEY UPDATE;

    IF FOUND AND situacao <> 'ABERTA' THEN
        RAISE EXCEPTION 'Contagem por forma só entra em sessão aberta.'
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;

    SELECT count(*), COALESCE(SUM(CASE WHEN tipo = 'ESTORNO' THEN -valor ELSE valor END), 0)
      INTO movimentos, esperado
    FROM movimentos_caixa
    WHERE empresa_id = NEW.empresa_id AND sessao_caixa_id = NEW.sessao_caixa_id AND forma = NEW.forma;

    IF movimentos = 0 THEN
        RAISE EXCEPTION 'A forma % não teve movimento nesta sessão.', NEW.forma
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;

    IF esperado <> NEW.valor_esperado THEN
        RAISE EXCEPTION 'O esperado da forma % não confere com os movimentos.', NEW.forma
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER tg_contagem_caixa_coerente
    BEFORE INSERT ON contagens_caixa
    FOR EACH ROW EXECUTE FUNCTION fn_contagem_caixa_coerente();

-- Conferencia por forma na sessao (complementa o tg_sessao_caixa_protegida da
-- V16, que continua valendo): ao sair de ABERTA, toda forma com movimento ja
-- foi contada; EM_CONFERENCIA exige diferenca em alguma forma; FECHADA com
-- diferenca em alguma forma exige a justificativa; no modo cego, a contagem
-- com diferenca em alguma forma passa pela conferencia.
CREATE FUNCTION fn_sessao_caixa_diferenca_por_forma() RETURNS trigger
    LANGUAGE plpgsql AS $$
DECLARE
    tem_diferenca BOOLEAN;
BEGIN
    -- Sessao aberta nao tem contagem; a fechada nao muda (o gatilho da V16 recusa).
    IF NEW.status = 'ABERTA' OR OLD.status = 'FECHADA' THEN
        RETURN NEW;
    END IF;

    IF OLD.status = 'ABERTA' AND EXISTS (
            SELECT 1
            FROM movimentos_caixa m
            WHERE m.empresa_id = NEW.empresa_id AND m.sessao_caixa_id = NEW.id AND m.forma <> 'DINHEIRO'
              AND NOT EXISTS (SELECT 1 FROM contagens_caixa c
                              WHERE c.sessao_caixa_id = m.sessao_caixa_id AND c.forma = m.forma)) THEN
        RAISE EXCEPTION 'Conte todas as formas de pagamento que tiveram movimento antes de fechar o caixa.'
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;

    -- Ao sair de ABERTA, a fotografia confere com os movimentos: o esperado
    -- do dinheiro (sangria e estorno subtraem) e o de cada forma contada
    -- (estorno subtrai).
    IF OLD.status = 'ABERTA' THEN
        IF NEW.valor_esperado IS DISTINCT FROM (
                SELECT COALESCE(SUM(CASE WHEN m.tipo IN ('SANGRIA', 'ESTORNO') THEN -m.valor ELSE m.valor END), 0)
                FROM movimentos_caixa m
                WHERE m.empresa_id = NEW.empresa_id AND m.sessao_caixa_id = NEW.id AND m.forma = 'DINHEIRO') THEN
            RAISE EXCEPTION 'O esperado em dinheiro não confere com os movimentos do caixa.'
                USING ERRCODE = 'integrity_constraint_violation';
        END IF;
        IF EXISTS (
                SELECT 1
                FROM contagens_caixa c
                WHERE c.empresa_id = NEW.empresa_id AND c.sessao_caixa_id = NEW.id
                  AND c.valor_esperado <> (
                      SELECT COALESCE(SUM(CASE WHEN m.tipo = 'ESTORNO' THEN -m.valor ELSE m.valor END), 0)
                      FROM movimentos_caixa m
                      WHERE m.empresa_id = c.empresa_id AND m.sessao_caixa_id = c.sessao_caixa_id
                        AND m.forma = c.forma)) THEN
            RAISE EXCEPTION 'O esperado de uma forma não confere com os movimentos do caixa.'
                USING ERRCODE = 'integrity_constraint_violation';
        END IF;
    END IF;

    tem_diferenca := COALESCE(NEW.diferenca <> 0, false) OR EXISTS (
        SELECT 1 FROM contagens_caixa c
        WHERE c.empresa_id = NEW.empresa_id AND c.sessao_caixa_id = NEW.id AND c.diferenca <> 0);

    IF NEW.status = 'EM_CONFERENCIA' AND NOT tem_diferenca THEN
        RAISE EXCEPTION 'Caixa em conferência exige diferença em alguma forma.'
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;

    IF NEW.status = 'FECHADA' AND tem_diferenca
            AND (NEW.justificativa IS NULL OR btrim(NEW.justificativa) = '') THEN
        RAISE EXCEPTION 'Caixa fechado com diferença exige a justificativa.'
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;

    IF OLD.status = 'ABERTA' AND NEW.status = 'FECHADA' AND NEW.fechamento_cego AND tem_diferenca THEN
        RAISE EXCEPTION 'No fechamento cego, a contagem com diferença passa pela conferência.'
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER tg_sessao_caixa_diferenca_por_forma
    BEFORE UPDATE ON sessoes_caixa
    FOR EACH ROW EXECUTE FUNCTION fn_sessao_caixa_diferenca_por_forma();

-- Venda coerente no commit (constraint trigger deferida): a venda, os itens e
-- os pagamentos sao gravados em comandos separados, entao as somas so podem
-- ser conferidas no fim da transacao. Ao menos um item; soma dos brutos =
-- subtotal; dos descontos dos itens = desconto_itens; dos rateados =
-- desconto_total; dos liquidos = total; pagamentos - troco = total; e o troco
-- nunca passa do dinheiro entregue.
CREATE FUNCTION fn_venda_coerente() RETURNS trigger
    LANGUAGE plpgsql AS $$
DECLARE
    alvo BIGINT;
    venda vendas%ROWTYPE;
    itens INTEGER;
    bruto NUMERIC;
    desconto_dos_itens NUMERIC;
    rateado NUMERIC;
    liquido NUMERIC;
    pago NUMERIC;
    dinheiro NUMERIC;
BEGIN
    IF TG_TABLE_NAME = 'vendas' THEN
        alvo := NEW.id;
    ELSE
        alvo := NEW.venda_id;
    END IF;

    SELECT * INTO venda FROM vendas WHERE id = alvo;
    IF NOT FOUND THEN
        RETURN NULL;
    END IF;

    SELECT count(*), COALESCE(SUM(valor_bruto), 0), COALESCE(SUM(desconto_item), 0),
           COALESCE(SUM(desconto_rateado), 0), COALESCE(SUM(valor_liquido), 0)
      INTO itens, bruto, desconto_dos_itens, rateado, liquido
    FROM itens_venda
    WHERE venda_id = alvo;

    SELECT COALESCE(SUM(valor), 0), COALESCE(SUM(valor) FILTER (WHERE forma = 'DINHEIRO'), 0)
      INTO pago, dinheiro
    FROM pagamentos_venda
    WHERE venda_id = alvo;

    IF itens = 0
            OR bruto <> venda.subtotal
            OR desconto_dos_itens <> venda.desconto_itens
            OR rateado <> venda.desconto_total
            OR liquido <> venda.total
            OR pago - venda.troco <> venda.total
            OR venda.troco > dinheiro THEN
        RAISE EXCEPTION 'Venda % incoerente: itens, descontos, pagamentos ou troco não somam os totais.', venda.numero
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;

    RETURN NULL;
END;
$$;

CREATE CONSTRAINT TRIGGER tg_venda_coerente
    AFTER INSERT ON vendas
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION fn_venda_coerente();

CREATE CONSTRAINT TRIGGER tg_item_venda_coerente
    AFTER INSERT ON itens_venda
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION fn_venda_coerente();

CREATE CONSTRAINT TRIGGER tg_pagamento_venda_coerente
    AFTER INSERT ON pagamentos_venda
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION fn_venda_coerente();

-- Estorno de caixa preso ao recebimento: so devolve o que a venda recebeu,
-- na mesma forma e com o mesmo valor.
CREATE FUNCTION fn_movimento_caixa_estorno_do_recebimento() RETURNS trigger
    LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.tipo = 'ESTORNO' AND NOT EXISTS (
            SELECT 1
            FROM movimentos_caixa r
            WHERE r.empresa_id = NEW.empresa_id AND r.venda_id = NEW.venda_id AND r.tipo = 'RECEBIMENTO'
              AND r.forma = NEW.forma AND r.valor = NEW.valor) THEN
        RAISE EXCEPTION 'Estorno sem o recebimento da venda na mesma forma e com o mesmo valor.'
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER tg_movimento_caixa_estorno_do_recebimento
    BEFORE INSERT ON movimentos_caixa
    FOR EACH ROW EXECUTE FUNCTION fn_movimento_caixa_estorno_do_recebimento();

-- Estorno de estoque preso a baixa: devolve exatamente o que a baixa do mesmo
-- item tirou (quantidade oposta). O tipo errado fica para o CHECK do motivo.
CREATE FUNCTION fn_movimento_estoque_estorno_da_baixa() RETURNS trigger
    LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.motivo = 'CANCELAMENTO_VENDA' AND NEW.tipo = 'ENTRADA' AND NOT EXISTS (
            SELECT 1
            FROM movimentos_estoque b
            WHERE b.empresa_id = NEW.empresa_id AND b.item_venda_id = NEW.item_venda_id AND b.motivo = 'VENDA'
              AND b.quantidade = -NEW.quantidade) THEN
        RAISE EXCEPTION 'Estorno de estoque sem a baixa do item com a mesma quantidade.'
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER tg_movimento_estoque_estorno_da_baixa
    BEFORE INSERT ON movimentos_estoque
    FOR EACH ROW EXECUTE FUNCTION fn_movimento_estoque_estorno_da_baixa();

-- Recebimento preso ao pagamento: a venda esta CONCLUIDA e tem o pagamento da
-- mesma forma, com o mesmo valor (no dinheiro, o entregue menos o troco).
-- Venda de outra empresa, forma fora da lista e valor nao positivo ficam para
-- as FKs e os CHECKs.
CREATE FUNCTION fn_movimento_caixa_recebimento_do_pagamento() RETURNS trigger
    LANGUAGE plpgsql AS $$
DECLARE
    venda vendas%ROWTYPE;
BEGIN
    IF NEW.tipo <> 'RECEBIMENTO' OR NEW.venda_id IS NULL OR NEW.valor <= 0
            OR NEW.forma NOT IN ('DINHEIRO', 'DEBITO', 'CREDITO', 'PIX') THEN
        RETURN NEW;
    END IF;

    SELECT * INTO venda FROM vendas WHERE empresa_id = NEW.empresa_id AND id = NEW.venda_id;
    IF NOT FOUND THEN
        RETURN NEW;
    END IF;

    IF venda.status <> 'CONCLUIDA' OR NOT EXISTS (
            SELECT 1
            FROM pagamentos_venda p
            WHERE p.venda_id = venda.id AND p.forma = NEW.forma
              AND NEW.valor = p.valor - CASE WHEN p.forma = 'DINHEIRO' THEN venda.troco ELSE 0 END) THEN
        RAISE EXCEPTION 'Recebimento sem o pagamento da venda concluída na mesma forma e com o mesmo valor.'
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER tg_movimento_caixa_recebimento_do_pagamento
    BEFORE INSERT ON movimentos_caixa
    FOR EACH ROW EXECUTE FUNCTION fn_movimento_caixa_recebimento_do_pagamento();

-- Baixa presa ao item: a baixa VENDA tira exatamente a quantidade de estoque do
-- item. Item de outra empresa fica para a FK.
CREATE FUNCTION fn_movimento_estoque_baixa_do_item() RETURNS trigger
    LANGUAGE plpgsql AS $$
DECLARE
    quantidade_do_item NUMERIC(12,3);
BEGIN
    IF NEW.motivo <> 'VENDA' OR NEW.item_venda_id IS NULL THEN
        RETURN NEW;
    END IF;

    SELECT quantidade_estoque INTO quantidade_do_item
    FROM itens_venda
    WHERE empresa_id = NEW.empresa_id AND id = NEW.item_venda_id;

    IF FOUND AND -NEW.quantidade <> quantidade_do_item THEN
        RAISE EXCEPTION 'Baixa de estoque diferente da quantidade do item vendido.'
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER tg_movimento_estoque_baixa_do_item
    BEFORE INSERT ON movimentos_estoque
    FOR EACH ROW EXECUTE FUNCTION fn_movimento_estoque_baixa_do_item();

-- Movimento de estoque da venda (baixa e estorno) e imutavel. Os outros
-- continuam como na V9 (a exclusao do produto apaga o estoque inicial do
-- cadastro).
CREATE FUNCTION fn_movimento_estoque_da_venda_imutavel() RETURNS trigger
    LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.origem = 'VENDA' THEN
        RAISE EXCEPTION 'Movimento de estoque da venda não pode ser alterado nem excluído.'
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;
    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER tg_movimento_estoque_da_venda_imutavel
    BEFORE UPDATE OR DELETE ON movimentos_estoque
    FOR EACH ROW EXECUTE FUNCTION fn_movimento_estoque_da_venda_imutavel();

-- Cancelamento coerente no commit (constraint triggers deferidas): todo
-- estorno (de caixa ou de estoque) e de venda CANCELADA, e a venda cancelada
-- tem um ESTORNO para cada RECEBIMENTO e um CANCELAMENTO_VENDA para cada baixa
-- VENDA dos itens.
CREATE FUNCTION fn_estorno_de_venda_cancelada() RETURNS trigger
    LANGUAGE plpgsql AS $$
DECLARE
    alvo BIGINT;
BEGIN
    IF TG_TABLE_NAME = 'movimentos_caixa' THEN
        alvo := NEW.venda_id;
    ELSE
        SELECT venda_id INTO alvo FROM itens_venda WHERE empresa_id = NEW.empresa_id AND id = NEW.item_venda_id;
    END IF;

    IF NOT EXISTS (SELECT 1 FROM vendas WHERE id = alvo AND status = 'CANCELADA') THEN
        RAISE EXCEPTION 'Estorno de uma venda que não foi cancelada.'
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;
    RETURN NULL;
END;
$$;

CREATE CONSTRAINT TRIGGER tg_estorno_de_caixa_de_venda_cancelada
    AFTER INSERT ON movimentos_caixa
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW
    WHEN (NEW.tipo = 'ESTORNO')
    EXECUTE FUNCTION fn_estorno_de_venda_cancelada();

CREATE CONSTRAINT TRIGGER tg_estorno_de_estoque_de_venda_cancelada
    AFTER INSERT ON movimentos_estoque
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW
    WHEN (NEW.motivo = 'CANCELAMENTO_VENDA')
    EXECUTE FUNCTION fn_estorno_de_venda_cancelada();

CREATE FUNCTION fn_venda_cancelada_completa() RETURNS trigger
    LANGUAGE plpgsql AS $$
BEGIN
    IF EXISTS (
            SELECT 1
            FROM movimentos_caixa r
            WHERE r.empresa_id = NEW.empresa_id AND r.venda_id = NEW.id AND r.tipo = 'RECEBIMENTO'
              AND NOT EXISTS (SELECT 1 FROM movimentos_caixa e
                              WHERE e.empresa_id = r.empresa_id AND e.venda_id = r.venda_id AND e.tipo = 'ESTORNO'
                                AND e.forma = r.forma AND e.valor = r.valor)) THEN
        RAISE EXCEPTION 'Venda % cancelada sem o estorno de todos os recebimentos.', NEW.numero
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;
    IF EXISTS (
            SELECT 1
            FROM movimentos_estoque b
            JOIN itens_venda i ON i.empresa_id = b.empresa_id AND i.id = b.item_venda_id
            WHERE i.venda_id = NEW.id AND b.motivo = 'VENDA'
              AND NOT EXISTS (SELECT 1 FROM movimentos_estoque c
                              WHERE c.empresa_id = b.empresa_id AND c.item_venda_id = b.item_venda_id
                                AND c.motivo = 'CANCELAMENTO_VENDA')) THEN
        RAISE EXCEPTION 'Venda % cancelada sem o estorno de todas as baixas de estoque.', NEW.numero
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;
    RETURN NULL;
END;
$$;

CREATE CONSTRAINT TRIGGER tg_venda_cancelada_completa
    AFTER UPDATE ON vendas
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW
    WHEN (OLD.status = 'CONCLUIDA' AND NEW.status = 'CANCELADA')
    EXECUTE FUNCTION fn_venda_cancelada_completa();
