        USING ERRCODE = 'integrity_constraint_violation';
END;
$$;

CREATE TRIGGER tg_item_venda_imutavel
    BEFORE UPDATE OR DELETE ON itens_venda
    FOR EACH ROW EXECUTE FUNCTION fn_item_venda_imutavel();

