-- V7: identificacao do produto (Fase B) -- multiplos codigos de barras por
-- produto, uuid publico, nome curto e fornecedor principal; remocao das
-- colunas antigas codigo_barras, categoria e unidade.
--
-- Migration aditiva (V1-V6 intactas). Ver
-- docs/modules/produtos-identificacao-e-formulario.md (secao 3) e DEC-032.
--
-- Convencoes:
--  * PK interna BIGINT identity (DEC-015), nunca exposta na API. O identificador
--    publico do produto passa a ser o uuid (DEC-019/029): na aplicacao ele e
--    gerado em Java; aqui o banco so o gera para os produtos ja existentes. O
--    DEFAULT da coluna e apenas rede de seguranca (mesmo padrao da V6).
--  * Isolamento por empresa (DEC-016): o codigo de barras pertence a mesma
--    empresa do produto, garantido pela FK COMPOSTA (empresa_id, produto_id)
--    -> produtos (empresa_id, id). A unicidade do codigo e por empresa.
--  * Os codigos sao parte do cadastro do produto: ON DELETE CASCADE.

-- =====================================================================
-- Passo 1: colunas novas de produtos e alvo da FK composta dos codigos.
-- =====================================================================
-- ADD COLUMN com DEFAULT volatil: o PostgreSQL avalia gen_random_uuid() por
-- linha, entao cada produto existente recebe um uuid proprio (spec 3.3, item 3).
ALTER TABLE produtos
    ADD COLUMN uuid       UUID         NOT NULL DEFAULT gen_random_uuid(),
    ADD COLUMN nome_curto VARCHAR(30),
    ADD COLUMN fornecedor VARCHAR(100),
    ADD CONSTRAINT uq_produto_uuid UNIQUE (uuid),
    ADD CONSTRAINT uq_produto_empresa_id UNIQUE (empresa_id, id),
    -- Defesa no banco alem da normalizacao do service (texto aparado; vazio
    -- vira NULL): nem vazio nem com espacos nas pontas.
    ADD CONSTRAINT ck_produto_nome_curto_valido
        CHECK (nome_curto IS NULL OR (nome_curto = btrim(nome_curto) AND nome_curto <> '')),
    ADD CONSTRAINT ck_produto_fornecedor_valido
        CHECK (fornecedor IS NULL OR (fornecedor = btrim(fornecedor) AND fornecedor <> ''));

-- =====================================================================
-- Passo 2: codigos de barras do produto (0..N; o limite de 20 e da aplicacao).
-- =====================================================================
CREATE TABLE produto_codigos_barras (
    id         BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id BIGINT      NOT NULL,
    produto_id BIGINT      NOT NULL,
    codigo     VARCHAR(50) NOT NULL,
    formato    VARCHAR(10) NOT NULL,
    ordem      SMALLINT    NOT NULL,
    criado_em  TIMESTAMP   NOT NULL DEFAULT now(),
    CONSTRAINT fk_codigo_barras_produto FOREIGN KEY (empresa_id, produto_id)
        REFERENCES produtos (empresa_id, id) ON DELETE CASCADE,
    -- O mesmo codigo nao pode estar em dois produtos da empresa nem duas vezes
    -- no mesmo produto. Empresas diferentes podem repetir o codigo.
    CONSTRAINT uq_codigo_barras_empresa UNIQUE (empresa_id, codigo),
    -- Defesa no banco alem da normalizacao do service: nao vazio e sem nenhum
    -- espaco em branco (\s: espaco, tab, quebra de linha), nas pontas ou interno
    -- (a mesma classe removida na normalizacao do Passo 3).
    CONSTRAINT ck_codigo_barras_codigo CHECK (codigo <> '' AND codigo !~ '\s'),
    CONSTRAINT ck_codigo_barras_formato CHECK (formato IN ('EAN8', 'UPCA', 'EAN13', 'OUTRO')),
    CONSTRAINT ck_codigo_barras_ordem CHECK (ordem >= 0)
);

-- Serve a listagem dos codigos do produto e o ON DELETE CASCADE.
CREATE INDEX idx_codigo_barras_produto ON produto_codigos_barras (produto_id);

-- =====================================================================
-- Passo 3: copia o codigo de barras atual de cada produto (spec 3.3, item 2).
-- =====================================================================
-- Normalizacao (spec 4.3): remove todo espaco em branco, inclusive interno
-- (\s cobre espaco, tab e quebra de linha). Codigo nulo, vazio ou so com
-- espacos nao gera linha.
--
-- Formato pelo conteudo: so digitos com tamanho 8/12/13 e digito verificador
-- GS1 (mod 10) correto -> EAN8/UPCA/EAN13. Qualquer outro caso -> OUTRO,
-- inclusive EAN com digito errado: o dado antigo e preservado, nunca perdido.
--
-- Digito GS1: numerando as posicoes da DIREITA para a esquerda a partir de 1
-- (o verificador e a posicao 1), as posicoes pares tem peso 3 e as impares
-- peso 1. O codigo e valido quando a soma ponderada de TODOS os digitos
-- (verificador incluso) e multipla de 10. A soma e calculada so para codigos
-- candidatos (so digitos e tamanho 8/12/13); para os demais fica NULL e o CASE
-- resulta em OUTRO.
--
-- Colisao depois da normalizacao (ex.: '789 1' e '7891' na mesma empresa)
-- viola uq_codigo_barras_empresa e aborta a migration de proposito: nenhum
-- codigo e descartado em silencio; o conflito deve ser resolvido no dado.
INSERT INTO produto_codigos_barras (empresa_id, produto_id, codigo, formato, ordem)
SELECT normalizado.empresa_id,
       normalizado.produto_id,
       normalizado.codigo,
       CASE
           WHEN gs1.soma_ponderada % 10 = 0 THEN
               CASE length(normalizado.codigo)
                   WHEN 8  THEN 'EAN8'
                   WHEN 12 THEN 'UPCA'
                   ELSE         'EAN13'
               END
           ELSE 'OUTRO'
       END,
       0
  FROM (SELECT p.empresa_id,
               p.id                                         AS produto_id,
               regexp_replace(p.codigo_barras, '\s', '', 'g') AS codigo
          FROM produtos p
         WHERE p.codigo_barras IS NOT NULL
       ) AS normalizado
 CROSS JOIN LATERAL (
        SELECT sum(substr(normalizado.codigo, posicao, 1)::int
                   * CASE WHEN (length(normalizado.codigo) - posicao + 1) % 2 = 0 THEN 3 ELSE 1 END
               ) AS soma_ponderada
          FROM generate_series(1, length(normalizado.codigo)) AS posicao
         WHERE normalizado.codigo ~ '^[0-9]+$'
           AND length(normalizado.codigo) IN (8, 12, 13)
       ) AS gs1
 WHERE normalizado.codigo <> ''
 ORDER BY normalizado.produto_id;

-- =====================================================================
-- Passo 4: remove as colunas antigas (spec 3.3, item 4).
-- codigo_barras ja foi copiado; categoria e unidade em texto foram
-- substituidas por categoria_id/unidade_id na V6 (Fase A).
-- =====================================================================
ALTER TABLE produtos
    DROP CONSTRAINT uq_produto_empresa_codigo_barras,
    DROP COLUMN codigo_barras,
    DROP COLUMN categoria,
    DROP COLUMN unidade;
