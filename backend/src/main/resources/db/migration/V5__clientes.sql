-- V5: cadastro de clientes (pessoa fisica), isolado por empresa.
--
-- Migration aditiva (V1-V4 intactas). Ver docs/modules/clientes.md e DEC-029.
--
-- Convencoes:
--  * PK interna BIGINT identity (DEC-015), nunca exposta na API. O identificador
--    publico e o uuid (DEC-019/029): gerado na aplicacao (UUID.randomUUID()) e
--    imutavel; o DEFAULT gen_random_uuid() (nativo no PostgreSQL 13+, sem
--    extensao) e apenas rede de seguranca.
--  * CPF, telefone e WhatsApp armazenados apenas com digitos (sem mascara).
--  * WhatsApp derivado: com telefone_e_whatsapp = true o WhatsApp e o proprio
--    telefone e a coluna whatsapp fica NULL; ela so guarda um numero diferente.

CREATE TABLE clientes (
    id                  BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid                UUID         NOT NULL DEFAULT gen_random_uuid(),
    empresa_id          BIGINT       NOT NULL,
    nome                VARCHAR(150) NOT NULL,
    cpf                 VARCHAR(11),
    telefone            VARCHAR(20),
    telefone_e_whatsapp BOOLEAN      NOT NULL DEFAULT true,
    whatsapp            VARCHAR(20),
    observacoes         VARCHAR(500),
    ativo               BOOLEAN      NOT NULL DEFAULT true,
    criado_em           TIMESTAMP    NOT NULL DEFAULT now(),
    atualizado_em       TIMESTAMP,
    CONSTRAINT fk_cliente_empresa FOREIGN KEY (empresa_id) REFERENCES empresa (id),
    CONSTRAINT uq_cliente_uuid UNIQUE (uuid),
    -- CPF unico por empresa, apenas quando informado: UNIQUE trata multiplos
    -- NULL como nao-conflitantes (mesmo padrao de SKU/codigo de barras).
    CONSTRAINT uq_cliente_empresa_cpf UNIQUE (empresa_id, cpf),
    -- Sem numero duplicado: whatsapp proprio so quando o telefone nao e WhatsApp.
    CONSTRAINT ck_cliente_whatsapp_coerente CHECK (telefone_e_whatsapp = false OR whatsapp IS NULL)
);

-- Indice para acelerar o lookup por empresa (mesmo padrao de idx_produto_empresa).
CREATE INDEX idx_cliente_empresa ON clientes (empresa_id);
