-- V16: caixa (etapa 10) -- pontos de caixa, configuracao do fechamento,
-- sessoes de caixa e movimentos de caixa imutaveis.
--
-- Migration aditiva (V1-V15 intactas, DEC-020). Ver docs/modules/caixa.md
-- (secao 4) e DEC-041.
--
-- Convencoes (as do estoque, V9):
--  * PK BIGINT identity mais uuid publico (DEC-015, DEC-019), gerado pela
--    aplicacao (sem DEFAULT).
--  * Isolamento por empresa (DEC-016) com FKs COMPOSTAS (empresa_id, ...) e
--    UNIQUE (empresa_id, id) como alvo.
--  * Dinheiro em NUMERIC(12,2).
--  * Diferenca de proposito: os horarios sao TIMESTAMPTZ e a aplicacao os
--    preenche com o Clock unico (America/Sao_Paulo); nenhuma coluna tem
--    DEFAULT now() (spec 4.5, primeira parte da DT-030). O unico now() abaixo
--    e o da carga do "Caixa 1".
--  * O dinheiro esperado na gaveta NAO e coluna: e a soma dos movimentos. Na
--    contagem, a sessao guarda a fotografia (esperado, contado, diferenca).
--  * Os gatilhos usam o SQLSTATE 23000 (integrity_constraint_violation): a
--    aplicacao os recebe como violacao de integridade, nunca como erro 500.

-- =====================================================================
-- Passo 1: pontos de caixa (a gaveta de um balcao).
-- =====================================================================
CREATE TABLE pontos_caixa (
    id            BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid          UUID         NOT NULL,
    empresa_id    BIGINT       NOT NULL,
    nome          VARCHAR(40)  NOT NULL,
    ativo         BOOLEAN      NOT NULL DEFAULT true,
    criado_em     TIMESTAMPTZ  NOT NULL,
    atualizado_em TIMESTAMPTZ,
    CONSTRAINT uq_ponto_caixa_uuid UNIQUE (uuid),
    CONSTRAINT uq_ponto_caixa_empresa_id UNIQUE (empresa_id, id),
    CONSTRAINT fk_ponto_caixa_empresa FOREIGN KEY (empresa_id) REFERENCES empresa (id),
    -- A aplicacao apara o nome; o banco recusa vazio e espacos nas pontas.
    CONSTRAINT ck_ponto_caixa_nome CHECK (nome = btrim(nome) AND nome <> '')
);

-- Nome unico na empresa sem diferenciar maiusculas, como categorias e marcas.
CREATE UNIQUE INDEX uq_ponto_caixa_nome ON pontos_caixa (empresa_id, lower(nome));

-- Carga: um "Caixa 1" ativo por empresa existente. Empresas novas ganham o
-- seu na primeira consulta de pontos (spec 3.1).
INSERT INTO pontos_caixa (empresa_id, uuid, nome, ativo, criado_em)
SELECT id, gen_random_uuid(), 'Caixa 1', true, now()
FROM empresa;

-- =====================================================================
-- Passo 2: configuracao do caixa (uma linha por empresa; sem linha vale o
-- padrao, fechamento cego ligado).
-- =====================================================================
CREATE TABLE configuracoes_caixa (
    empresa_id      BIGINT      PRIMARY KEY,
    fechamento_cego BOOLEAN     NOT NULL DEFAULT true,
    atualizado_por  BIGINT      NOT NULL,
    atualizado_em   TIMESTAMPTZ NOT NULL,
    CONSTRAINT fk_configuracao_caixa_empresa FOREIGN KEY (empresa_id) REFERENCES empresa (id),
    -- Alvo uq_usuario_empresa_id (V8).
    CONSTRAINT fk_configuracao_caixa_usuario FOREIGN KEY (empresa_id, atualizado_por)
        REFERENCES usuario (empresa_id, id)
);

-- =====================================================================
-- Passo 3: sessoes de caixa (da abertura ao fechamento num ponto).
-- =====================================================================
CREATE TABLE sessoes_caixa (
    id              BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid            UUID          NOT NULL,
    empresa_id      BIGINT        NOT NULL,
    ponto_caixa_id  BIGINT        NOT NULL,
    status          VARCHAR(15)   NOT NULL,
    aberta_por      BIGINT        NOT NULL,
    aberta_em       TIMESTAMPTZ   NOT NULL,
    fundo_troco     NUMERIC(12,2) NOT NULL,
    -- Modo que valia na contagem; NULL antes dela.
    fechamento_cego BOOLEAN,
    -- Fotografia da contagem; NULL antes dela.
    valor_esperado  NUMERIC(12,2),
    valor_contado   NUMERIC(12,2),
    diferenca       NUMERIC(12,2),
    contada_por     BIGINT,
    contada_em      TIMESTAMPTZ,
    justificativa   VARCHAR(500),
    fechada_por     BIGINT,
    fechada_em      TIMESTAMPTZ,
    CONSTRAINT uq_sessao_caixa_uuid UNIQUE (uuid),
    CONSTRAINT uq_sessao_caixa_empresa_id UNIQUE (empresa_id, id),
    CONSTRAINT fk_sessao_caixa_ponto FOREIGN KEY (empresa_id, ponto_caixa_id)
        REFERENCES pontos_caixa (empresa_id, id) ON DELETE RESTRICT,
    -- Usuarios nao sao excluidos fisicamente: RESTRICT (padrao). As FKs de
    -- contagem e fechamento sao MATCH SIMPLE: com a coluna NULL, nao conferem.
    CONSTRAINT fk_sessao_caixa_aberta_por FOREIGN KEY (empresa_id, aberta_por)
        REFERENCES usuario (empresa_id, id),
    CONSTRAINT fk_sessao_caixa_contada_por FOREIGN KEY (empresa_id, contada_por)
        REFERENCES usuario (empresa_id, id),
    CONSTRAINT fk_sessao_caixa_fechada_por FOREIGN KEY (empresa_id, fechada_por)
        REFERENCES usuario (empresa_id, id),
    CONSTRAINT ck_sessao_caixa_status CHECK (status IN ('ABERTA', 'EM_CONFERENCIA', 'FECHADA')),
    CONSTRAINT ck_sessao_caixa_fundo_troco CHECK (fundo_troco >= 0),
    CONSTRAINT ck_sessao_caixa_valor_contado CHECK (valor_contado >= 0),
    CONSTRAINT ck_sessao_caixa_diferenca CHECK (diferenca = valor_contado - valor_esperado),
    -- Coerencia por estado, escrita como implicacoes (um status fora da lista
    -- cai no ck_sessao_caixa_status).
    CONSTRAINT ck_sessao_caixa_aberta CHECK (
        status <> 'ABERTA' OR (
            fechamento_cego IS NULL AND valor_esperado IS NULL AND valor_contado IS NULL AND diferenca IS NULL
            AND contada_por IS NULL AND contada_em IS NULL
            AND justificativa IS NULL AND fechada_por IS NULL AND fechada_em IS NULL)),
    CONSTRAINT ck_sessao_caixa_em_conferencia CHECK (
        status <> 'EM_CONFERENCIA' OR (
            fechamento_cego IS NOT NULL AND valor_esperado IS NOT NULL AND valor_contado IS NOT NULL
            AND diferenca IS NOT NULL AND contada_por IS NOT NULL AND contada_em IS NOT NULL
            AND diferenca <> 0
            AND justificativa IS NULL AND fechada_por IS NULL AND fechada_em IS NULL)),
    CONSTRAINT ck_sessao_caixa_fechada CHECK (
        status <> 'FECHADA' OR (
            fechamento_cego IS NOT NULL AND valor_esperado IS NOT NULL AND valor_contado IS NOT NULL
            AND diferenca IS NOT NULL AND contada_por IS NOT NULL AND contada_em IS NOT NULL
            AND fechada_por IS NOT NULL AND fechada_em IS NOT NULL)),
    -- Diferenca no fechamento exige justificativa nao vazia (spec 3.4).
    CONSTRAINT ck_sessao_caixa_justificativa CHECK (
        status <> 'FECHADA' OR diferenca = 0 OR (justificativa IS NOT NULL AND btrim(justificativa) <> ''))
);

-- No maximo uma sessao aberta (ou em conferencia) por ponto e por usuario. A
-- aplicacao identifica a violacao pelo nome do indice (spec 3.8).
CREATE UNIQUE INDEX uq_sessao_caixa_ponto_aberta
    ON sessoes_caixa (empresa_id, ponto_caixa_id)
    WHERE status IN ('ABERTA', 'EM_CONFERENCIA');

CREATE UNIQUE INDEX uq_sessao_caixa_usuario_aberta
    ON sessoes_caixa (empresa_id, aberta_por)
    WHERE status IN ('ABERTA', 'EM_CONFERENCIA');

-- Historico das sessoes da empresa, da mais recente (desempate por id, a
-- mesma ordem das consultas).
CREATE INDEX ix_sessao_caixa_historico ON sessoes_caixa (empresa_id, aberta_em DESC, id DESC);

-- Ultimo fundo de troco do ponto (LATERAL ... LIMIT 1) e a FK RESTRICT do ponto.
CREATE INDEX ix_sessao_caixa_ponto ON sessoes_caixa (empresa_id, ponto_caixa_id, aberta_em DESC, id DESC);

-- =====================================================================
-- Passo 4: movimentos de caixa (so recebem insercoes).
-- =====================================================================
CREATE TABLE movimentos_caixa (
    id                 BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid               UUID          NOT NULL,
    empresa_id         BIGINT        NOT NULL,
    sessao_caixa_id    BIGINT        NOT NULL,
    tipo               VARCHAR(15)   NOT NULL,
    -- Sempre positivo: o sinal sai do tipo (SANGRIA subtrai).
    valor              NUMERIC(12,2) NOT NULL,
    motivo             VARCHAR(200),
    usuario_id         BIGINT        NOT NULL,
    -- Chave enviada pela tela (um UUID por abertura da janela).
    chave_idempotencia UUID          NOT NULL,
    criado_em          TIMESTAMPTZ   NOT NULL,
    CONSTRAINT uq_movimento_caixa_uuid UNIQUE (uuid),
    CONSTRAINT fk_movimento_caixa_sessao FOREIGN KEY (empresa_id, sessao_caixa_id)
        REFERENCES sessoes_caixa (empresa_id, id) ON DELETE RESTRICT,
    CONSTRAINT fk_movimento_caixa_usuario FOREIGN KEY (empresa_id, usuario_id)
        REFERENCES usuario (empresa_id, id),
    CONSTRAINT uq_movimento_caixa_chave UNIQUE (empresa_id, chave_idempotencia),
    CONSTRAINT ck_movimento_caixa_tipo CHECK (tipo IN ('ABERTURA', 'SUPRIMENTO', 'SANGRIA')),
    CONSTRAINT ck_movimento_caixa_valor CHECK (
        (tipo = 'ABERTURA' AND valor >= 0) OR (tipo <> 'ABERTURA' AND valor > 0)),
    -- Motivo aparado e obrigatorio em suprimento e sangria; nulo na abertura.
    CONSTRAINT ck_movimento_caixa_motivo CHECK (
        (tipo = 'ABERTURA' AND motivo IS NULL)
        OR (tipo <> 'ABERTURA' AND motivo IS NOT NULL AND motivo = btrim(motivo) AND motivo <> ''))
);

-- Uma abertura por sessao.
CREATE UNIQUE INDEX uq_movimento_caixa_abertura
    ON movimentos_caixa (empresa_id, sessao_caixa_id)
    WHERE tipo = 'ABERTURA';

-- Soma do esperado e lista dos movimentos da sessao; FK RESTRICT da sessao.
CREATE INDEX ix_movimento_caixa_sessao ON movimentos_caixa (empresa_id, sessao_caixa_id, id);

-- =====================================================================
-- Passo 5: imutabilidade garantida no banco (spec 4.4).
-- =====================================================================
CREATE FUNCTION fn_movimento_caixa_imutavel() RETURNS trigger
    LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'Movimento de caixa não pode ser alterado nem excluído.'
        USING ERRCODE = 'integrity_constraint_violation';
END;
$$;

CREATE TRIGGER tg_movimento_caixa_imutavel
    BEFORE UPDATE OR DELETE ON movimentos_caixa
    FOR EACH ROW EXECUTE FUNCTION fn_movimento_caixa_imutavel();

-- Movimento so entra em sessao ABERTA: depois da contagem o esperado e uma
-- fotografia e nao pode mudar. O FOR SHARE espera um fechamento em andamento
-- na mesma sessao terminar. A aplicacao ja trava a sessao (FOR UPDATE) antes
-- de inserir; o PDV, ao gravar os recebimentos da venda, deve fazer o mesmo:
-- travar a sessao antes de inserir o movimento. Sessao inexistente na empresa
-- fica para a FK fk_movimento_caixa_sessao recusar.
CREATE FUNCTION fn_movimento_caixa_em_sessao_aberta() RETURNS trigger
    LANGUAGE plpgsql AS $$
DECLARE
    situacao VARCHAR(15);
BEGIN
    SELECT status INTO situacao
    FROM sessoes_caixa
    WHERE empresa_id = NEW.empresa_id AND id = NEW.sessao_caixa_id
    FOR SHARE;

    IF FOUND AND situacao <> 'ABERTA' THEN
        RAISE EXCEPTION 'Movimento de caixa só entra em sessão aberta.'
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER tg_movimento_caixa_em_sessao_aberta
    BEFORE INSERT ON movimentos_caixa
    FOR EACH ROW EXECUTE FUNCTION fn_movimento_caixa_em_sessao_aberta();

-- Sessao: nasce ABERTA; nunca excluida; fechada nao muda; a abertura nao
-- muda; a contagem gravada nao muda; so as transicoes ABERTA -> EM_CONFERENCIA,
-- ABERTA -> FECHADA e EM_CONFERENCIA -> FECHADA; no modo cego, contagem com
-- diferenca passa pela conferencia (nunca ABERTA -> FECHADA direto).
CREATE FUNCTION fn_sessao_caixa_protegida() RETURNS trigger
    LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        IF NEW.status <> 'ABERTA' THEN
            RAISE EXCEPTION 'Sessão de caixa nasce aberta.'
                USING ERRCODE = 'integrity_constraint_violation';
        END IF;
        RETURN NEW;
    END IF;

    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'Sessão de caixa não pode ser excluída.'
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;

    IF OLD.status = 'FECHADA' THEN
        RAISE EXCEPTION 'Sessão de caixa fechada não pode ser alterada.'
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;

    IF NEW.id IS DISTINCT FROM OLD.id
            OR NEW.uuid IS DISTINCT FROM OLD.uuid
            OR NEW.empresa_id IS DISTINCT FROM OLD.empresa_id
            OR NEW.ponto_caixa_id IS DISTINCT FROM OLD.ponto_caixa_id
            OR NEW.aberta_por IS DISTINCT FROM OLD.aberta_por
            OR NEW.aberta_em IS DISTINCT FROM OLD.aberta_em
            OR NEW.fundo_troco IS DISTINCT FROM OLD.fundo_troco THEN
        RAISE EXCEPTION 'Os dados da abertura do caixa não podem ser alterados.'
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;

    IF OLD.status <> 'ABERTA'
            AND (NEW.fechamento_cego, NEW.valor_esperado, NEW.valor_contado, NEW.diferenca,
                 NEW.contada_por, NEW.contada_em)
                IS DISTINCT FROM
                (OLD.fechamento_cego, OLD.valor_esperado, OLD.valor_contado, OLD.diferenca,
                 OLD.contada_por, OLD.contada_em) THEN
        RAISE EXCEPTION 'A contagem do caixa não pode ser alterada.'
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;

    IF NEW.status IS DISTINCT FROM OLD.status
            AND NOT ((OLD.status = 'ABERTA' AND NEW.status IN ('EM_CONFERENCIA', 'FECHADA'))
                     OR (OLD.status = 'EM_CONFERENCIA' AND NEW.status = 'FECHADA')) THEN
        RAISE EXCEPTION 'Mudança de situação do caixa não permitida.'
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;

    IF OLD.status = 'ABERTA' AND NEW.status = 'FECHADA' AND NEW.fechamento_cego AND NEW.diferenca <> 0 THEN
        RAISE EXCEPTION 'No fechamento cego, a contagem com diferença passa pela conferência.'
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER tg_sessao_caixa_protegida
    BEFORE INSERT OR UPDATE OR DELETE ON sessoes_caixa
    FOR EACH ROW EXECUTE FUNCTION fn_sessao_caixa_protegida();
