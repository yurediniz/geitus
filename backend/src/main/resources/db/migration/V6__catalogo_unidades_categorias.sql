-- V6: cadastros de unidades de medida e categorias (arvore) por empresa, e
-- conversao dos textos livres produtos.unidade / produtos.categoria em FKs.
--
-- Migration aditiva (V1-V5 intactas). Ver docs/modules/categorias-e-unidades.md
-- (secao 6) e DEC-030/031.
--
-- Convencoes:
--  * PK interna BIGINT identity (DEC-015), nunca exposta na API. O identificador
--    publico e o uuid (DEC-019/029): na aplicacao ele e gerado em Java; aqui, a
--    migration e o unico lugar em que o banco gera o uuid (gen_random_uuid(),
--    nativo no PostgreSQL 13+). O DEFAULT da coluna e apenas rede de seguranca.
--  * Isolamento por empresa (DEC-016): unidades, categorias e os vinculos do
--    produto sao sempre resolvidos dentro da mesma empresa do produto.
--  * As colunas antigas produtos.unidade e produtos.categoria sao PRESERVADAS
--    (rede de seguranca ate a Fase B); a aplicacao deixa de le-las e escreve-las.

-- =====================================================================
-- Passo 1a: unidades de medida.
-- =====================================================================
CREATE TABLE unidades_medida (
    id            BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid          UUID        NOT NULL DEFAULT gen_random_uuid(),
    empresa_id    BIGINT      NOT NULL,
    sigla         VARCHAR(20) NOT NULL,
    descricao     VARCHAR(60) NOT NULL,
    fracionada    BOOLEAN     NOT NULL DEFAULT false,
    ativo         BOOLEAN     NOT NULL DEFAULT true,
    criado_em     TIMESTAMP   NOT NULL DEFAULT now(),
    atualizado_em TIMESTAMP,
    CONSTRAINT fk_unidade_empresa FOREIGN KEY (empresa_id) REFERENCES empresa (id),
    CONSTRAINT uq_unidade_uuid UNIQUE (uuid),
    -- Sigla unica por empresa; o indice (empresa_id, sigla) tambem serve a FK
    -- de empresa e a listagem ordenada por sigla.
    CONSTRAINT uq_unidade_empresa_sigla UNIQUE (empresa_id, sigla),
    -- Defesa no banco alem da normalizacao do service: sigla sempre maiuscula.
    CONSTRAINT ck_unidade_sigla_maiuscula CHECK (sigla = upper(sigla))
);

-- =====================================================================
-- Passo 1b: categorias em arvore (parent_id NULL = raiz).
-- FK do pai SEM ON DELETE CASCADE: excluir categoria com filhos e bloqueado
-- pela regra de negocio e o banco garante.
-- =====================================================================
CREATE TABLE categorias (
    id            BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid          UUID         NOT NULL DEFAULT gen_random_uuid(),
    empresa_id    BIGINT       NOT NULL,
    parent_id     BIGINT,
    nome          VARCHAR(100) NOT NULL,
    ativo         BOOLEAN      NOT NULL DEFAULT true,
    criado_em     TIMESTAMP    NOT NULL DEFAULT now(),
    atualizado_em TIMESTAMP,
    CONSTRAINT fk_categoria_empresa FOREIGN KEY (empresa_id) REFERENCES empresa (id),
    CONSTRAINT fk_categoria_pai FOREIGN KEY (parent_id) REFERENCES categorias (id),
    CONSTRAINT uq_categoria_uuid UNIQUE (uuid)
);

-- Nome unico entre irmaos, sem diferenciar maiusculas. COALESCE(parent_id, 0)
-- faz as raizes (parent_id NULL) colidirem entre si: sem ele, NULLs nunca
-- conflitam. O prefixo empresa_id tambem serve a FK de empresa.
CREATE UNIQUE INDEX uq_categoria_irmaos ON categorias (empresa_id, COALESCE(parent_id, 0), lower(nome));

-- Serve a FK do pai e a contagem de subcategorias.
CREATE INDEX idx_categoria_pai ON categorias (parent_id);

-- =====================================================================
-- Passo 2: as 10 unidades padrao para cada empresa existente.
-- (Empresas novas recebem as mesmas unidades pelo codigo da aplicacao.)
-- =====================================================================
INSERT INTO unidades_medida (uuid, empresa_id, sigla, descricao, fracionada)
SELECT gen_random_uuid(), e.id, padrao.sigla, padrao.descricao, padrao.fracionada
  FROM empresa e
 CROSS JOIN (VALUES
        ('UN',  'Unidade',    false),
        ('KG',  'Quilograma', true),
        ('G',   'Grama',      true),
        ('L',   'Litro',      true),
        ('ML',  'Mililitro',  true),
        ('M',   'Metro',      true),
        ('CX',  'Caixa',      false),
        ('PCT', 'Pacote',     false),
        ('DZ',  'Dúzia',      false),
        ('FD',  'Fardo',      false)
      ) AS padrao (sigla, descricao, fracionada);

-- =====================================================================
-- Passos 3 e 4: unidade do produto (texto -> FK).
-- =====================================================================
ALTER TABLE produtos
    ADD COLUMN unidade_id BIGINT;

-- 3a. Textos reconhecidos: a propria sigla padrao ou um sinonimo (spec 6.3).
-- Chave de comparacao: upper(trim(unidade)) com acentos removidos por
-- translate(). Assim 'PÇ'/'PEÇA'/'DÚZIA' e as grafias sem acento casam com a
-- mesma lista, e o resultado nao depende de o upper() do locale do banco
-- converter letras acentuadas (no locale C ele so converte ASCII: 'pç' -> 'Pç').
UPDATE produtos p
   SET unidade_id = u.id
  FROM (VALUES
        ('UN', 'UN'), ('KG', 'KG'), ('G', 'G'), ('L', 'L'), ('ML', 'ML'),
        ('M', 'M'), ('CX', 'CX'), ('PCT', 'PCT'), ('DZ', 'DZ'), ('FD', 'FD'),
        ('UND', 'UN'), ('UNID', 'UN'), ('UNIDADE', 'UN'), ('UNIDADES', 'UN'),
        ('KILO', 'KG'), ('KILOS', 'KG'), ('QUILO', 'KG'), ('KGS', 'KG'),
        ('LT', 'L'), ('LTS', 'L'), ('LITRO', 'L'), ('LITROS', 'L'),
        ('PC', 'UN'), ('PECA', 'UN'),
        ('CAIXA', 'CX'),
        ('PACOTE', 'PCT'),
        ('DUZIA', 'DZ'),
        ('FARDO', 'FD')
      ) AS sinonimo (texto, sigla),
       unidades_medida u
 WHERE translate(upper(trim(p.unidade)),
                 'ÁÀÂÃÉÊÍÓÔÕÚÜÇáàâãéêíóôõúüç',
                 'AAAAEEIOOOUUCAAAAEEIOOOUUC') = sinonimo.texto
   AND u.empresa_id = p.empresa_id
   AND u.sigla = sinonimo.sigla;

-- 3b. Textos nao reconhecidos viram unidades novas, uma por (empresa, sigla):
-- sigla = upper(trim(unidade)); descricao = texto aparado do produto de MENOR
-- id do grupo (DISTINCT ON + ORDER BY ... id). Nao fracionada (default).
-- ON CONFLICT: defesa caso a sigla ja exista na empresa (nao ocorre com as
-- unidades padrao, que ja foram casadas em 3a).
INSERT INTO unidades_medida (uuid, empresa_id, sigla, descricao)
SELECT gen_random_uuid(), novo.empresa_id, novo.sigla, novo.descricao
  FROM (SELECT DISTINCT ON (p.empresa_id, upper(trim(p.unidade)))
               p.empresa_id,
               upper(trim(p.unidade)) AS sigla,
               trim(p.unidade)        AS descricao
          FROM produtos p
         WHERE p.unidade_id IS NULL
           AND trim(p.unidade) <> ''
         ORDER BY p.empresa_id, upper(trim(p.unidade)), p.id
       ) AS novo
ON CONFLICT ON CONSTRAINT uq_unidade_empresa_sigla DO NOTHING;

UPDATE produtos p
   SET unidade_id = u.id
  FROM unidades_medida u
 WHERE p.unidade_id IS NULL
   AND trim(p.unidade) <> ''
   AND u.empresa_id = p.empresa_id
   AND u.sigla = upper(trim(p.unidade));

-- 4. Produto sem unidade (NULL, vazio ou so espacos) recebe UN da sua empresa.
UPDATE produtos p
   SET unidade_id = u.id
  FROM unidades_medida u
 WHERE p.unidade_id IS NULL
   AND u.empresa_id = p.empresa_id
   AND u.sigla = 'UN';

ALTER TABLE produtos
    ALTER COLUMN unidade_id SET NOT NULL,
    ADD CONSTRAINT fk_produto_unidade FOREIGN KEY (unidade_id) REFERENCES unidades_medida (id);

CREATE INDEX idx_produto_unidade ON produtos (unidade_id);

-- =====================================================================
-- Passos 5 e 6: categoria do produto (texto -> FK).
-- =====================================================================

-- 5. Cada lower(trim(categoria)) distinto por empresa vira UMA categoria raiz,
-- com o nome aparado do produto de MENOR id do grupo. Vazios sao ignorados.
INSERT INTO categorias (uuid, empresa_id, nome)
SELECT gen_random_uuid(), raiz.empresa_id, raiz.nome
  FROM (SELECT DISTINCT ON (p.empresa_id, lower(trim(p.categoria)))
               p.empresa_id,
               trim(p.categoria) AS nome,
               p.id              AS primeiro_produto_id
          FROM produtos p
         WHERE trim(p.categoria) <> ''
         ORDER BY p.empresa_id, lower(trim(p.categoria)), p.id
       ) AS raiz
 ORDER BY raiz.primeiro_produto_id;

-- 6. Vincula o produto a raiz da sua empresa com o mesmo nome normalizado.
ALTER TABLE produtos
    ADD COLUMN categoria_id BIGINT;

UPDATE produtos p
   SET categoria_id = c.id
  FROM categorias c
 WHERE trim(p.categoria) <> ''
   AND c.empresa_id = p.empresa_id
   AND c.parent_id IS NULL
   AND lower(c.nome) = lower(trim(p.categoria));

ALTER TABLE produtos
    ADD CONSTRAINT fk_produto_categoria FOREIGN KEY (categoria_id) REFERENCES categorias (id);

CREATE INDEX idx_produto_categoria ON produtos (categoria_id);

-- =====================================================================
-- Passo 7: unidade de compra e fator de conversao (nulos para todos).
-- =====================================================================
ALTER TABLE produtos
    ADD COLUMN unidade_compra_id BIGINT,
    ADD COLUMN fator_conversao   NUMERIC(12,4),
    ADD CONSTRAINT fk_produto_unidade_compra FOREIGN KEY (unidade_compra_id) REFERENCES unidades_medida (id),
    ADD CONSTRAINT ck_produto_fator_positivo CHECK (fator_conversao IS NULL OR fator_conversao > 0),
    -- Unidade de compra e fator andam juntos: ambos nulos ou ambos preenchidos.
    ADD CONSTRAINT ck_produto_compra_coerente CHECK ((unidade_compra_id IS NULL) = (fator_conversao IS NULL));

CREATE INDEX idx_produto_unidade_compra ON produtos (unidade_compra_id);

-- Passo 8: produtos.unidade e produtos.categoria permanecem intactas (sem
-- ALTER/UPDATE nelas); serao removidas numa migration da Fase B.
